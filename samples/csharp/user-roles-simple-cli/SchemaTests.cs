using Datasources;

namespace UserRolesSimpleCli.Tests;

public sealed class SchemaTests
{
    [Theory]
    [InlineData("sqlite")]
    [InlineData("mysql")]
    [InlineData("postgres")]
    public void CreatesTablesWithForeignKeys(string provider)
    {
        var sql = string.Join("\n", Schema.Tables(provider, ColumnTypes.Map(provider)).Select(table => table.GetText()));
        Assert.Contains("FOREIGN KEY (user_id) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (group_id) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (bad_role_id) REFERENCES", sql);
        Assert.Contains("ugly_name", sql);
        Assert.DoesNotContain("password", UsersRolesGroupsQuery.Create(provider).GetText());
    }

    [Fact]
    public void SqliteUsesIntegerPrimaryKey() =>
        Assert.Contains("id INTEGER PRIMARY KEY", Schema.Tables("sqlite", ColumnTypes.Map("sqlite"))[0].GetText());

    [Fact]
    public void MysqlUsesAutoIncrement() =>
        Assert.Contains("AUTO_INCREMENT", Schema.Tables("mysql", ColumnTypes.Map("mysql"))[0].GetText());

    [Fact]
    public void PostgresUsesIdentity() =>
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", Schema.Tables("postgres", ColumnTypes.Map("postgres"))[0].GetText());

    [Fact]
    public void MapsAndRejectsUnknownProvider()
    {
        Assert.Equal("INTEGER", ColumnTypes.Map("sqlite")("int"));
        Assert.Equal("INT", ColumnTypes.Map("mysql")("int"));
        Assert.Equal("BOOLEAN", ColumnTypes.Map("postgres")("bool"));
        Assert.Throws<InvalidOperationException>(() => ColumnTypes.Map("oracle"));
        Assert.Throws<InvalidOperationException>(() => Schema.Tables("oracle", _ => "X")[0].GetText());
    }

    [Fact]
    public void QuotesIdentifiersAndMapsColumnTypes()
    {
        Assert.Equal("\"user\"", Schema.Ident("sqlite", "user"));
        Assert.Equal("\"a\"\"b\"", Schema.Ident("postgres", "a\"b"));
        Assert.Equal("`a``b`", Schema.Ident("mysql", "a`b"));
        Assert.Equal("\"users\".\"id\"", Schema.Qualified("sqlite", "users.id"));
        Assert.Equal("`users`.`id`", Schema.Qualified("mysql", "users.id"));

        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("string"));
        Assert.Equal("INTEGER", ColumnTypes.Map("sqlite")("bool"));
        Assert.Equal("NUMERIC", ColumnTypes.Map("sqlite")("decimal"));
        Assert.Equal("REAL", ColumnTypes.Map("sqlite")("float"));
        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("datetime"));
        Assert.Equal("BLOB", ColumnTypes.Map("sqlite")("binary"));
        Assert.Contains("Unknown sqlite type \"xml\"", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("sqlite")("xml")).Message);

        Assert.Equal("CHAR(36)", ColumnTypes.Map("mysql")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("mysql")("string"));
        Assert.Equal("TINYINT", ColumnTypes.Map("mysql")("bool"));
        Assert.Equal("DECIMAL(18,4)", ColumnTypes.Map("mysql")("decimal"));
        Assert.Equal("DOUBLE", ColumnTypes.Map("mysql")("float"));
        Assert.Equal("TEXT", ColumnTypes.Map("mysql")("datetime"));
        Assert.Equal("BLOB", ColumnTypes.Map("mysql")("binary"));
        Assert.Contains("Unknown mysql type \"xml\"", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("mysql")("xml")).Message);

        Assert.Equal("UUID", ColumnTypes.Map("postgres")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("postgres")("string"));
        Assert.Equal("NUMERIC", ColumnTypes.Map("postgres")("decimal"));
        Assert.Equal("DOUBLE PRECISION", ColumnTypes.Map("postgres")("float"));
        Assert.Equal("TIMESTAMPTZ", ColumnTypes.Map("postgres")("datetime"));
        Assert.Equal("BYTEA", ColumnTypes.Map("postgres")("binary"));
        Assert.Contains("Unknown postgres type \"xml\"", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("postgres")("xml")).Message);

        Assert.Equal(
            "CREATE TABLE \"user\" (\"id\" INTEGER PRIMARY KEY, \"uuid\" TEXT, \"username\" TEXT, \"is_enabled\" INTEGER, \"balance\" NUMERIC, \"location\" REAL, \"created\" TEXT, \"version\" BLOB)",
            UserTable("sqlite"));
        Assert.Equal(
            "CREATE TABLE `user` (`id` INT PRIMARY KEY, `uuid` CHAR(36), `username` TEXT, `is_enabled` TINYINT, `balance` DECIMAL(18,4), `location` DOUBLE, `created` TEXT, `version` BLOB)",
            UserTable("mysql"));
        Assert.Equal(
            "CREATE TABLE \"user\" (\"id\" INTEGER PRIMARY KEY, \"uuid\" UUID, \"username\" TEXT, \"is_enabled\" BOOLEAN, \"balance\" NUMERIC, \"location\" DOUBLE PRECISION, \"created\" TIMESTAMPTZ, \"version\" BYTEA)",
            UserTable("postgres"));
    }

    static string UserTable(string provider)
    {
        (string Name, string Type, bool Id)[] columns =
        [
            ("id", "int", true),
            ("uuid", "uuid", false),
            ("username", "string", false),
            ("is_enabled", "bool", false),
            ("balance", "decimal", false),
            ("location", "float", false),
            ("created", "datetime", false),
            ("version", "binary", false),
        ];
        var map = ColumnTypes.Map(provider);
        return new CreateTableStatement(
            Schema.Ident(provider, "user"),
            columns.Select(column => new Column(
                Schema.Ident(provider, column.Name),
                column.Id ? $"{map(column.Type)} PRIMARY KEY" : map(column.Type))).ToArray()).GetText();
    }

    [Fact]
    public void MapsUglyColumns()
    {
        Assert.Equal("ugly_name", Columns.Names.Map("name"));
        Assert.Equal("bad_role_id", Columns.Names.Map("role_id"));
        Assert.Equal("username", Columns.Names.Map("username"));
        Assert.Equal("name", Columns.Names.ReverseMap("ugly_name"));
        Assert.Equal("role_id", Columns.Names.ReverseMap("bad_role_id"));
        Assert.Equal("username", Columns.Names.ReverseMap("username"));
    }

    [Fact]
    public void PrefixesCreateTableIfNotExists()
    {
        Assert.Equal("CREATE TABLE IF NOT EXISTS users (id INT)", Migrate.IfNotExists("CREATE TABLE users (id INT)"));
        Assert.Equal("SELECT 1", Migrate.IfNotExists("SELECT 1"));
    }

    [Fact]
    public void MysqlProceduresWriteMappedColumns()
    {
        var sql = string.Join("\n", Schema.MysqlProcedures());
        Assert.Contains("INSERT INTO `groups` (ugly_name", sql);
        Assert.Contains("INSERT INTO `user_roles` (user_id, bad_role_id", sql);
    }

    [Fact]
    public void JoinSelectMatchesContract() =>
        Assert.Equal(
            "SELECT \"users\".id AS id, \"users\".username AS username, \"users\".is_enabled AS is_enabled, \"users\".created AS created, \"roles\".id AS role_id, \"roles\".name AS role_name, \"roles\".is_enabled AS role_is_enabled, \"groups\".id AS group_id, \"groups\".ugly_name AS group_name, \"groups\".is_enabled AS group_is_enabled FROM \"users\" LEFT JOIN \"user_roles\" ON \"users\".id = \"user_roles\".user_id LEFT JOIN \"roles\" ON \"user_roles\".bad_role_id = \"roles\".id LEFT JOIN \"user_groups\" ON \"users\".id = \"user_groups\".user_id LEFT JOIN \"groups\" ON \"user_groups\".group_id = \"groups\".id ORDER BY \"users\".id ASC, \"roles\".id ASC, \"groups\".id ASC",
            UsersRolesGroupsQuery.Create("sqlite").GetText());
}
