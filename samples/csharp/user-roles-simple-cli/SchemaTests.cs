using Datasources;

namespace UserRolesSimpleCli.Tests;

public sealed class SchemaTests
{
    [Theory]
    [InlineData("sqlite")]
    [InlineData("mysql")]
    [InlineData("postgres")]
    public void CreatesTablesWithForeignKeys(string provider)
    {
        var sql = string.Join("\n", Schema.Tables(provider, ColumnTypes.Map(provider)).Select(table => table.GetText()));
        Assert.Contains("FOREIGN KEY (user_id) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (group_id) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (bad_role_id) REFERENCES", sql);
        Assert.Contains("ugly_name", sql);
        Assert.DoesNotContain("password", UsersRolesGroupsQuery.Create(provider).GetText());
    }

    [Fact]
    public void SqliteUsesIntegerPrimaryKey() =>
        Assert.Contains("id INTEGER PRIMARY KEY", Schema.Tables("sqlite", ColumnTypes.Map("sqlite"))[0].GetText());

    [Fact]
    public void MysqlUsesAutoIncrement() =>
        Assert.Contains("AUTO_INCREMENT", Schema.Tables("mysql", ColumnTypes.Map("mysql"))[0].GetText());

    [Fact]
    public void PostgresUsesIdentity() =>
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", Schema.Tables("postgres", ColumnTypes.Map("postgres"))[0].GetText());

    [Fact]
    public void MapsAndRejectsUnknownProvider()
    {
        Assert.Equal("INTEGER", ColumnTypes.Map("sqlite")("int"));
        Assert.Equal("INT", ColumnTypes.Map("mysql")("int"));
        Assert.Equal("BOOLEAN", ColumnTypes.Map("postgres")("bool"));
        Assert.Throws<InvalidOperationException>(() => ColumnTypes.Map("oracle"));
        Assert.Throws<InvalidOperationException>(() => Schema.Tables("oracle", _ => "X")[0].GetText());
    }

    [Fact]
    public void MapsUglyColumns()
    {
        Assert.Equal("ugly_name", Columns.Names.Map("name"));
        Assert.Equal("bad_role_id", Columns.Names.Map("role_id"));
        Assert.Equal("username", Columns.Names.Map("username"));
        Assert.Equal("name", Columns.Names.ReverseMap("ugly_name"));
        Assert.Equal("role_id", Columns.Names.ReverseMap("bad_role_id"));
        Assert.Equal("username", Columns.Names.ReverseMap("username"));
    }

    [Fact]
    public void PrefixesCreateTableIfNotExists()
    {
        Assert.Equal("CREATE TABLE IF NOT EXISTS users (id INT)", Migrate.IfNotExists("CREATE TABLE users (id INT)"));
        Assert.Equal("SELECT 1", Migrate.IfNotExists("SELECT 1"));
    }

    [Fact]
    public void MysqlProceduresWriteMappedColumns()
    {
        var sql = string.Join("\n", Schema.MysqlProcedures());
        Assert.Contains("INSERT INTO `groups` (ugly_name", sql);
        Assert.Contains("INSERT INTO `user_roles` (user_id, bad_role_id", sql);
    }

    [Fact]
    public void JoinSelectMatchesContract() =>
        Assert.Equal(
            "SELECT \"users\".id AS id, \"users\".username AS username, \"users\".is_enabled AS is_enabled, \"users\".created AS created, \"roles\".id AS role_id, \"roles\".name AS role_name, \"roles\".is_enabled AS role_is_enabled, \"groups\".id AS group_id, \"groups\".ugly_name AS group_name, \"groups\".is_enabled AS group_is_enabled FROM \"users\" LEFT JOIN \"user_roles\" ON \"users\".id = \"user_roles\".user_id LEFT JOIN \"roles\" ON \"user_roles\".bad_role_id = \"roles\".id LEFT JOIN \"user_groups\" ON \"users\".id = \"user_groups\".user_id LEFT JOIN \"groups\" ON \"user_groups\".group_id = \"groups\".id",
            UsersRolesGroupsQuery.Create("sqlite").GetText());
}
