using Datasources;

namespace ContactsCrudEnrichedMediumRest.Tests;

public sealed class SchemaTests
{
    [Theory]
    [InlineData("sqlite")]
    [InlineData("mysql")]
    [InlineData("postgres")]
    public void CreatesPhysicalTablesWithForeignKeys(string provider)
    {
        var sql = string.Join("\n", Schema.Tables(provider).Select(table => table.GetText()));
        Assert.Contains("tbl_Contacts", sql);
        Assert.Contains("m_FirstName", sql);
        Assert.Contains("FOREIGN KEY (ContactSourceId) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (m_ContactTypeId) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (m_AddressTypeId) REFERENCES", sql);
        Assert.Contains("FOREIGN KEY (PhoneTypeId) REFERENCES", sql);
        Assert.Contains("UNIQUE (ContactId, ContactGroupId)", sql);
        Assert.DoesNotContain("first_name", sql);
    }

    [Fact]
    public void SqliteUsesIntegerPrimaryKey() =>
        Assert.Contains("Id INTEGER PRIMARY KEY", Schema.Tables("sqlite")[0].GetText());

    [Fact]
    public void MysqlUsesAutoIncrement() =>
        Assert.Contains("AUTO_INCREMENT", Schema.Tables("mysql")[0].GetText());

    [Fact]
    public void PostgresUsesIdentity() =>
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", Schema.Tables("postgres")[0].GetText());

    [Fact]
    public void LegacyKeyIsThePrimaryKey()
    {
        var sqlite = Schema.Tables("sqlite").Single(table => table.GetText().Contains("legacy_contact")).GetText();
        var mysql = Schema.Tables("mysql").Single(table => table.GetText().Contains("legacy_contact")).GetText();
        Assert.Contains("m_Key TEXT PRIMARY KEY", sqlite);
        Assert.Contains("PRIMARY KEY (m_Key)", mysql);
    }

    [Fact]
    public void QuotesIdentifiersAndRejectsUnknownProviders()
    {
        Assert.Equal("\"tbl_Contacts\"", Schema.Ident("sqlite", "tbl_Contacts"));
        Assert.Equal("\"a\"\"b\"", Schema.Ident("postgres", "a\"b"));
        Assert.Equal("`a``b`", Schema.Ident("mysql", "a`b"));
        Assert.Throws<InvalidOperationException>(() => Schema.Tables("oracle"));
        Assert.Throws<InvalidOperationException>(() => ColumnTypes.Map("oracle"));
    }

    [Fact]
    public void MapsColumnTypes()
    {
        Assert.Equal("INTEGER", ColumnTypes.Map("sqlite")("int"));
        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("string"));
        Assert.Equal("INTEGER", ColumnTypes.Map("sqlite")("bool"));
        Assert.Equal("NUMERIC", ColumnTypes.Map("sqlite")("decimal"));
        Assert.Equal("REAL", ColumnTypes.Map("sqlite")("float"));
        Assert.Equal("TEXT", ColumnTypes.Map("sqlite")("datetime"));
        Assert.Equal("BLOB", ColumnTypes.Map("sqlite")("binary"));
        Assert.Contains("Unknown sqlite type", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("sqlite")("xml")).Message);

        Assert.Equal("INT", ColumnTypes.Map("mysql")("int"));
        Assert.Equal("CHAR(36)", ColumnTypes.Map("mysql")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("mysql")("string"));
        Assert.Equal("TINYINT", ColumnTypes.Map("mysql")("bool"));
        Assert.Equal("DECIMAL(18,4)", ColumnTypes.Map("mysql")("decimal"));
        Assert.Equal("DOUBLE", ColumnTypes.Map("mysql")("float"));
        Assert.Equal("TEXT", ColumnTypes.Map("mysql")("datetime"));
        Assert.Equal("BLOB", ColumnTypes.Map("mysql")("binary"));
        Assert.Contains("Unknown mysql type", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("mysql")("xml")).Message);

        Assert.Equal("INTEGER", ColumnTypes.Map("postgres")("int"));
        Assert.Equal("UUID", ColumnTypes.Map("postgres")("uuid"));
        Assert.Equal("TEXT", ColumnTypes.Map("postgres")("string"));
        Assert.Equal("BOOLEAN", ColumnTypes.Map("postgres")("bool"));
        Assert.Equal("NUMERIC", ColumnTypes.Map("postgres")("decimal"));
        Assert.Equal("DOUBLE PRECISION", ColumnTypes.Map("postgres")("float"));
        Assert.Equal("TIMESTAMPTZ", ColumnTypes.Map("postgres")("datetime"));
        Assert.Equal("BYTEA", ColumnTypes.Map("postgres")("binary"));
        Assert.Contains("Unknown postgres type", Assert.Throws<DatasourceException>(() => ColumnTypes.Map("postgres")("xml")).Message);
    }

    [Fact]
    public void MapsPhysicalNamesInBothDirections()
    {
        Assert.Equal("m_FirstName", Names.Column("first_name"));
        Assert.Equal("tbl_Contacts", Names.Table("contacts"));
        Assert.Equal("first_name", Names.Columns.ReverseMap("m_FirstName"));
        Assert.Equal("contacts", Names.Tables.ReverseMap("tbl_Contacts"));
        Assert.Equal("zzz", Names.Column("zzz"));
        Assert.Equal("zzz", Names.Table("zzz"));
    }
}
