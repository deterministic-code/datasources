fn row(pairs: &[(&str, Value)]) -> Row {
    pairs
        .iter()
        .map(|(key, value)| ((*key).to_string(), value.clone()))
        .collect()
}

fn mapped(pairs: &[(&str, MappedValue)]) -> MappedRow {
    pairs
        .iter()
        .map(|(key, value)| ((*key).to_string(), value.clone()))
        .collect()
}

#[test]
fn parses_commands() {
    let s = |value: &str| value.to_string();
    assert_eq!(
        parse::args(&[s("add-user"), s("a"), s("b")]).unwrap(),
        CliCommand::AddUser {
            username: "a".into(),
            password: "b".into()
        }
    );
    assert_eq!(
        parse::args(&[s("add-role"), s("admin")]).unwrap(),
        CliCommand::AddRole { name: "admin".into() }
    );
    assert_eq!(
        parse::args(&[s("add-group"), s("staff")]).unwrap(),
        CliCommand::AddGroup { name: "staff".into() }
    );
    assert_eq!(
        parse::args(&[s("add-user-role"), s("a"), s("admin")]).unwrap(),
        CliCommand::AddUserRole {
            username: "a".into(),
            role: "admin".into()
        }
    );
    assert_eq!(
        parse::args(&[s("add-user-group"), s("a"), s("staff")]).unwrap(),
        CliCommand::AddUserGroup {
            username: "a".into(),
            group: "staff".into()
        }
    );
    assert_eq!(
        parse::args(&[s("enable-user"), s("a")]).unwrap(),
        CliCommand::EnableUser {
            username: "a".into()
        }
    );
    assert_eq!(
        parse::args(&[s("disable-user"), s("a")]).unwrap(),
        CliCommand::DisableUser {
            username: "a".into()
        }
    );
    assert_eq!(
        parse::args(&[s("list-users-roles-groups")]).unwrap(),
        CliCommand::ListUsersRolesGroups
    );
    for verb in [
        "add-user",
        "add-role",
        "add-group",
        "add-user-role",
        "add-user-group",
        "enable-user",
        "disable-user",
        "nope",
    ] {
        assert!(parse::args(&[s(verb)]).is_err());
    }
    assert!(parse::args(&[]).is_err());
    assert!(parse::args(&[s("add-user"), s("a"), s("b"), s("extra")]).is_err());
    assert!(parse::args(&[s("list-users-roles-groups"), s("extra")]).is_err());
}

#[test]
fn builds_schema() {
    for provider in ["sqlite", "mysql", "postgres"] {
        let sql = schema::tables(provider)
            .unwrap()
            .iter()
            .map(Text::get_text)
            .collect::<Vec<_>>()
            .join("\n");
        assert!(sql.contains("FOREIGN KEY (user_id) REFERENCES"));
        assert!(sql.contains("FOREIGN KEY (bad_role_id) REFERENCES"));
        assert!(sql.contains("ugly_name"));
    }
    assert!(schema::tables("sqlite")
        .unwrap()[0]
        .get_text()
        .contains("INTEGER PRIMARY KEY"));
    assert!(schema::tables("mysql")
        .unwrap()[0]
        .get_text()
        .contains("AUTO_INCREMENT"));
    assert!(schema::tables("postgres")
        .unwrap()[0]
        .get_text()
        .contains("GENERATED BY DEFAULT AS IDENTITY"));
    assert_eq!(column_types::map_type("sqlite", "int").unwrap(), "INTEGER");
    assert!(column_types::map("oracle").is_err());
    assert!(schema::tables("oracle").is_err());
    assert_eq!(columns::map("name"), "ugly_name");
    assert_eq!(columns::map("role_id"), "bad_role_id");
    assert_eq!(columns::map("username"), "username");
    assert_eq!(columns::reverse_map("ugly_name"), "name");
    assert_eq!(columns::reverse_map("bad_role_id"), "role_id");
    assert_eq!(columns::reverse_map("username"), "username");
    assert_eq!(
        migrate::if_not_exists("CREATE TABLE users (id INT)"),
        "CREATE TABLE IF NOT EXISTS users (id INT)"
    );
    assert_eq!(migrate::if_not_exists("SELECT 1"), "SELECT 1");
    assert!(schema::mysql_procedures()
        .join("\n")
        .contains("INSERT INTO `groups` (ugly_name"));
    assert_eq!(
        users_roles_groups_query::text("sqlite"),
        "SELECT \"users\".id AS id, \"users\".username AS username, \"users\".is_enabled AS is_enabled, \"users\".created AS created, \"roles\".id AS role_id, \"roles\".name AS role_name, \"roles\".is_enabled AS role_is_enabled, \"groups\".id AS group_id, \"groups\".ugly_name AS group_name, \"groups\".is_enabled AS group_is_enabled FROM \"users\" LEFT JOIN \"user_roles\" ON \"users\".id = \"user_roles\".user_id LEFT JOIN \"roles\" ON \"user_roles\".bad_role_id = \"roles\".id LEFT JOIN \"user_groups\" ON \"users\".id = \"user_groups\".user_id LEFT JOIN \"groups\" ON \"user_groups\".group_id = \"groups\".id"
    );
}

