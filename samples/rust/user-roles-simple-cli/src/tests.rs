#[tokio::test]
async fn migrates_and_rejects_missing() {
    let sqlite = MockCommand::new();
    migrate::apply(&sqlite, "sqlite").await.unwrap();
    assert!(sqlite
        .execute_logs
        .lock()
        .expect("mock")
        .iter()
        .all(|(text, _)| text.starts_with("CREATE TABLE IF NOT EXISTS")));
    let mysql = MockCommand::new();
    migrate::apply(&mysql, "mysql").await.unwrap();
    assert!(mysql
        .execute_logs
        .lock()
        .expect("mock")
        .iter()
        .any(|(text, _)| text.contains("CREATE PROCEDURE add_user")));
    let command = MockCommand::new();
    *command.reader_rows.lock().expect("mock") = vec![];
    let app = App::new(&command, "sqlite");
    assert!(app
        .run(CliCommand::EnableUser {
            username: "missing".into()
        })
        .await
        .is_err());
    *command.reader_rows.lock().expect("mock") = vec![row(&[("id", Value::Text("x".into()))])];
    assert!(app
        .run(CliCommand::EnableUser {
            username: "bad".into()
        })
        .await
        .is_err());
}

