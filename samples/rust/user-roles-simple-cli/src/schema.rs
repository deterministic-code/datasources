use crate::column_types;
use datasources::{
    Column, ColumnDefault, CreateTableStatement, ForeignKey, NotNull, PrimaryKey, Result,
    TableConstraint,
};

pub fn ident(provider: &str, name: &str) -> String {
    quote(provider, name)
}

pub fn qualified(provider: &str, name: &str) -> String {
    name.split('.')
        .map(|part| quote(provider, part))
        .collect::<Vec<_>>()
        .join(".")
}

fn quote(provider: &str, id: &str) -> String {
    match provider {
        "mysql" => format!("`{}`", id.replace('`', "``")),
        _ => format!("\"{}\"", id.replace('"', "\"\"")),
    }
}

fn id_type(provider: &str, mapped: String) -> String {
    match provider {
        "sqlite" => format!("{mapped} PRIMARY KEY"),
        "mysql" => format!("{mapped} AUTO_INCREMENT"),
        _ => format!("{mapped} GENERATED BY DEFAULT AS IDENTITY"),
    }
}

fn id_key(provider: &str, name: &str) -> Vec<TableConstraint> {
    match provider {
        "sqlite" => vec![],
        _ => vec![PrimaryKey::new(name, &["id"])],
    }
}

fn required() -> NotNull {
    NotNull::new(None)
}

pub fn tables(provider: &str) -> Result<Vec<CreateTableStatement>> {
    let map = column_types::map(provider)?;
    let id = id_type(provider, map("int")?);
    let text = map("string")?;
    let flag = map("bool")?;
    let created = map("datetime")?;
    let updated = map("binary")?;
    let enabled = ColumnDefault::new(if provider == "postgres" { "TRUE" } else { "1" }, None);
    let users = ident(provider, "users");
    let roles = ident(provider, "roles");
    let groups = ident(provider, "groups");
    let user_groups = ident(provider, "user_groups");
    let user_roles = ident(provider, "user_roles");
    Ok(vec![
        CreateTableStatement::new(
            &users,
            &[
                Column::new("id", &id),
                Column::new("username", &text).not_null(required()),
                Column::new("password", &text).not_null(required()),
                Column::new("is_enabled", &flag)
                    .default(enabled.clone())
                    .not_null(required()),
                Column::new("created", &created).not_null(required()),
                Column::new("updated", &updated).not_null(required()),
            ],
            &id_key(provider, "pk_users"),
        ),
        CreateTableStatement::new(
            &roles,
            &[
                Column::new("id", &id),
                Column::new("name", &text).not_null(required()),
                Column::new("is_enabled", &flag)
                    .default(enabled.clone())
                    .not_null(required()),
                Column::new("created", &created).not_null(required()),
                Column::new("updated", &updated).not_null(required()),
            ],
            &id_key(provider, "pk_roles"),
        ),
        CreateTableStatement::new(
            &groups,
            &[
                Column::new("id", &id),
                Column::new("ugly_name", &text).not_null(required()),
                Column::new("is_enabled", &flag)
                    .default(enabled.clone())
                    .not_null(required()),
                Column::new("created", &created).not_null(required()),
                Column::new("updated", &updated).not_null(required()),
            ],
            &id_key(provider, "pk_groups"),
        ),
        CreateTableStatement::new(
            &user_groups,
            &[
                Column::new("id", &id),
                Column::new("user_id", map("int")?).not_null(required()),
                Column::new("group_id", map("int")?).not_null(required()),
                Column::new("created", &created).not_null(required()),
                Column::new("updated", &updated).not_null(required()),
            ],
            &[
                id_key(provider, "pk_user_groups"),
                vec![
                    ForeignKey::new("fk_user_groups_user", &["user_id"], &users, &["id"], None, None),
                    ForeignKey::new(
                        "fk_user_groups_group",
                        &["group_id"],
                        &groups,
                        &["id"],
                        None,
                        None,
                    ),
                ],
            ]
            .concat(),
        ),
        CreateTableStatement::new(
            &user_roles,
            &[
                Column::new("id", &id),
                Column::new("user_id", map("int")?).not_null(required()),
                Column::new("bad_role_id", map("int")?).not_null(required()),
                Column::new("created", &created).not_null(required()),
                Column::new("updated", &updated).not_null(required()),
            ],
            &[
                id_key(provider, "pk_user_roles"),
                vec![
                    ForeignKey::new("fk_user_roles_user", &["user_id"], &users, &["id"], None, None),
                    ForeignKey::new(
                        "fk_user_roles_role",
                        &["bad_role_id"],
                        &roles,
                        &["id"],
                        None,
                        None,
                    ),
                ],
            ]
            .concat(),
        ),
    ])
}

