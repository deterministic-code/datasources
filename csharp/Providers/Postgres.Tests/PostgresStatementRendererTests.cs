using Datasources;
using Datasources.Postgres;

namespace Datasources.Postgres.Tests;

public class PostgresStatementRendererTests
{
    static StatementTextRenderer Renderer { get; } =
        new(t => new PostgresStatementRenderer(t));

    [Fact]
    public void RendersInsertedIdAndCreateTable()
    {
        Assert.Equal(
            "SELECT setval(pg_get_serial_sequence('users', 'id'), COALESCE((SELECT MAX(\"id\") FROM users), 1)) AS id",
            Renderer.Render(new SelectInsertedIdStatement("users", "id")));

        var create = new CreateTableStatement(
            "orders",
            [
                new Column("id", "INTEGER", new ColumnDefault("0", "df_id"), new NotNull("nn_id")),
                new Column("user_id", "INTEGER")
            ],
            [
                new PrimaryKey("pk_orders", ["id"]),
                new ForeignKey("fk_orders_user", ["user_id"], "users", ["id"], ReferentialAction.Cascade)
            ]);
        Assert.Equal(Renderer.Render(create), new PostgresCreateTableStatementRenderer().Render(create));
        Assert.Equal(
            "SELECT id FROM users",
            Renderer.Render(new SelectStatement(new() { Table = "users", Fields = ["id"] })));
    }

    [Fact]
    public void RendersTypeDefaultAndIdentity()
    {
        var create = new CreateTableStatement("users",
        [
            new Column("id", "int", Identity: true),
            new Column("is_enabled", "bool", new ColumnDefault("1")),
            new Column("is_disabled", "bool", new ColumnDefault("0", "df_off")),
            new Column("amount", "decimal", new ColumnDefault("1")),
            new Column("flag", "bool", new ColumnDefault("true"))
        ]);
        Assert.Equal(
            "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY, is_enabled BOOLEAN DEFAULT TRUE, is_disabled BOOLEAN CONSTRAINT df_off DEFAULT FALSE, amount NUMERIC DEFAULT 1, flag BOOLEAN DEFAULT true)",
            Renderer.Render(create));
        Assert.Equal(
            "CREATE TABLE users (id int, is_enabled bool DEFAULT 1, is_disabled bool CONSTRAINT df_off DEFAULT 0, amount decimal DEFAULT 1, flag bool DEFAULT true)",
            DefaultStatementTextRenderer.Instance.Render(create));
    }

    [Fact]
    public void RendersBulkUpdateWithColumnTypes()
    {
        var update = new BulkUpdateStatement(
            "parents",
            ["label"],
            ["id"],
            [
                ([new Parameter("label", new Value.Text("a"))], [new Parameter("id", new Value.Int(1))]),
                ([new Parameter("label", new Value.Text("b"))], [new Parameter("id", new Value.Int(2))])
            ]);
        Assert.Equal(
            "UPDATE parents SET label = data.label FROM (SELECT $label__0::TEXT AS label, $id__0::INTEGER AS id UNION ALL SELECT $label__1::TEXT AS label, $id__1::INTEGER AS id) AS data WHERE parents.id = data.id",
            Renderer.Render(update));
    }

    [Fact]
    public void RendersBulkUpdateIsoCreatedAsTimestamptz()
    {
        var update = new BulkUpdateStatement(
            "contacts",
            ["created"],
            ["id"],
            [
                ([new Parameter("created", new Value.Text("2020-01-02T03:04:05.000Z"))], [new Parameter("id", new Value.Int(1))])
            ]);
        Assert.Equal(
            "UPDATE contacts SET created = data.created FROM (SELECT $created__0::TIMESTAMPTZ AS created, $id__0::INTEGER AS id) AS data WHERE contacts.id = data.id",
            Renderer.Render(update));
    }

    [Fact]
    public void RendersBulkUpdateBase64VersionAsBytea()
    {
        var update = new BulkUpdateStatement(
            "contacts",
            ["version"],
            ["id"],
            [
                ([new Parameter("version", new Value.Text("AA=="))], [new Parameter("id", new Value.Int(1))])
            ]);
        Assert.Equal(
            "UPDATE contacts SET version = data.version FROM (SELECT $version__0::BYTEA AS version, $id__0::INTEGER AS id) AS data WHERE contacts.id = data.id",
            Renderer.Render(update));
    }

    [Fact]
    public void RendersCreateReadUpdateStoredProcedureStatements()
    {
        Assert.Contains("CREATE OR REPLACE FUNCTION CreateUsers", Renderer.Render(
            new CreateCreateStoredProcedureStatement("CreateUsers", "users", ["id", "name"], [new RoutineParameter("name", "TEXT")], "id", "INT", ["name"])));
        Assert.Contains("ORDER BY t.id", Renderer.Render(
            new CreateReadStoredProcedureStatement("ReadUsers", "users", ["id", "name"], [], "id", "INT", [], [])));
        Assert.Contains("jsonb_to_recordset", Renderer.Render(
            new CreateBulkDeleteStoredProcedureStatement(
                "BulkDeleteUsers",
                "users",
                [new RoutineParameter("id", "INT")],
                new RoutineParameter("payload", "jsonb"),
                "id",
                "INT")));
    }
}
