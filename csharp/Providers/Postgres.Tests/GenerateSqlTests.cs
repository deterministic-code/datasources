using Datasources.CodeGenerators;

namespace Datasources.Postgres.Tests;

public class GenerateSqlTests
{
    const string TypesYaml = """
        types:
          - user:
              tags: [datasource_type]
              inherits: set
              fields:
                - email:
                    type: string
                - created:
                    type: datetime
                - updated:
                    type: datetime
        """;

    static Dictionary<string, string> Files(string types, string? datasource = null, string? seeds = null)
    {
        var files = new Dictionary<string, string> { ["types.yaml"] = types };
        if (datasource is not null) files["datasource.yaml"] = datasource;
        if (seeds is not null) files["datasource_seeds.yaml"] = seeds;
        return files;
    }

    static IReadOnlyList<string> Names(IReadOnlyList<GenerateEntry> entries) =>
        entries.Select(e => e.Filename).OrderBy(n => n, StringComparer.Ordinal).ToList();

    static string AddedTypes(string types) => $"types.yaml:\n  added: true\n  content:\n{Indent(types, 4)}";

    static string Document(string path, string yaml) => $"{path}:\n{Indent(yaml, 2)}";

    static string Indent(string yaml, int spaces)
    {
        var pad = new string(' ', spaces);
        return string.Join('\n', yaml.Trim().Split('\n').Select(line => pad + line)) + "\n";
    }

    [Fact]
    public void EmitsStoredProcedureMigrationsWhenTheFlagIsTrueOnPostgres()
    {
        var files = Names(GenerateSql.Of(Files(TypesYaml), new Dictionary<string, string> { ["datasource.use_stored_procedures"] = "true" }, ["postgres"]));
        Assert.Contains("postgres/migrations/0001_initial_up.sql", files);
        Assert.Contains("postgres/migrations/0002_stored_procedures_up.sql", files);
        Assert.Contains("postgres/migrations/0002_stored_procedures_down.sql", files);
        var up = GenerateSql.Of(Files(TypesYaml), new Dictionary<string, string> { ["datasource.use_stored_procedures"] = "true" }, ["postgres"])
            .Single(e => e.Filename.EndsWith("_stored_procedures_up.sql")).Content;
        Assert.Contains("read_users", up);
        Assert.Contains("bulk_create_users", up);
        Assert.Contains("CREATE OR REPLACE", up);
    }

    [Fact]
    public void OmitsStoredProcedureMigrationsWhenTheFlagIsAbsent()
    {
        var files = Names(GenerateSql.Of(Files(TypesYaml), new Dictionary<string, string>(), ["postgres"]));
        Assert.Contains("postgres/migrations/0001_initial_up.sql", files);
        Assert.DoesNotContain(files, f => f.Contains("stored_procedures"));
    }

    const string IdentityYaml = """
        types:
          - person:
              tags: [datasource_type]
              inherits: set
              fields:
                - id:
                    type: integer
                    is_id: true
                - code:
                    type: integer
                - email:
                    type: string
          - link:
              tags: [datasource_type]
              inherits: set
              ids: [left_id, right_id]
              fields:
                - left_id:
                    type: integer
                - right_id:
                    type: integer
          - country:
              tags: [datasource_type]
              inherits: set
              fields:
                - name:
                    type: string
        """;

    const string IdentityDatasource = """
        includes:
          - types:
              filter: tag == "datasource_type"
        types:
          - country:
              fields:
                - id:
                    is_fixed_id: true
                    is_readonly: true
        """;

    static string UpBody()
    {
        var entries = GenerateSql.Of(Files(IdentityYaml, IdentityDatasource), new Dictionary<string, string>(), ["postgres"]);
        return entries.Single(e => e.Filename.EndsWith("0001_initial_up.sql")).Content;
    }

    [Fact]
    public void UsesIsIdAsAGeneratedPrimaryKey()
    {
        var sql = UpBody();
        Assert.Matches("CREATE TABLE \"people\"", sql);
        Assert.Matches("\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.Matches("CONSTRAINT \"people_primary_key\" PRIMARY KEY", sql);
        Assert.Matches("\"code\" INTEGER NOT NULL", sql);
        Assert.Matches("\"email\"", sql);
    }

    [Fact]
    public void EmitsACompositePrimaryKeyWhenIdsListsMultipleColumns()
    {
        var sql = UpBody();
        Assert.Matches("CREATE TABLE \"links\"", sql);
        Assert.Matches("\"left_id\" INTEGER NOT NULL", sql);
        Assert.Matches("\"right_id\" INTEGER NOT NULL", sql);
        Assert.Matches(@"CONSTRAINT ""links_primary_key"" PRIMARY KEY \(""left_id"", ""right_id""\)", sql);
        Assert.DoesNotMatch(@"CREATE TABLE ""links""[\s\S]*GENERATED BY DEFAULT AS IDENTITY", sql);
    }

    [Fact]
    public void EmitsAPlainPrimaryKeyWhenIsFixedIdIsSet()
    {
        var sql = UpBody();
        Assert.Matches("CREATE TABLE \"countries\"", sql);
        Assert.Matches("\"id\" INTEGER NOT NULL", sql);
        Assert.Matches(@"CONSTRAINT ""countries_primary_key"" PRIMARY KEY \(""id""\)", sql);
        Assert.DoesNotMatch(@"CREATE TABLE ""countries""[\s\S]*GENERATED BY DEFAULT AS IDENTITY", sql);
    }

    [Fact]
    public void ReplacesStoredProceduresWhenALaterVersionAddsAColumn()
    {
        const string first = "version-20261016T000000Z-001/diff.yaml";
        const string second = "version-20261016T000000Z-002/diff.yaml";
        const string nextYaml = """
            types:
              - user:
                  tags: [datasource_type]
                  inherits: set
                  fields:
                    - email:
                        type: string
                    - created:
                        type: datetime
                    - updated:
                        type: datetime
                    - notes:
                        type: string
            """;
        var files = Files(nextYaml);
        files[first] = AddedTypes(TypesYaml);
        files[second] = Document("types.yaml", nextYaml);
        var entries = GenerateSql.Of(files, new Dictionary<string, string> { ["datasource.use_stored_procedures"] = "true" }, ["postgres"]);
        var up2 = entries.Single(e => e.Filename == "postgres/migrations/0002_up.sql").Content;
        var down2 = entries.Single(e => e.Filename == "postgres/migrations/0002_down.sql").Content;
        Assert.Contains("notes", up2);
        Assert.Contains("CREATE OR REPLACE", up2);
        Assert.Contains("CREATE OR REPLACE", down2);
    }
}
