using System.Globalization;

namespace Datasources.Postgres;

internal sealed class PostgresCreateTableStatementRenderer : CreateTableStatementTextRenderer
{
    protected override string Type(Column column) =>
        PostgresDriver.ColumnTypes.TryGetValue(column.Type, out var sql) ? sql : column.Type;

    protected override string Default(Column column) =>
        column.Default is { } value && Literal(column.Type, value.Value) is { } literal
            ? base.Default(column with { Default = value with { Value = literal } })
            : base.Default(column);

    protected override string Identity(Column column) =>
        column.Identity ? " GENERATED BY DEFAULT AS IDENTITY" : "";

    static string? Literal(string type, string raw) =>
        PostgresRowTypeConverters.All.TryGetValue(type, out var converter)
        && long.TryParse(raw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var number)
            ? converter.Convert(number) switch
            {
                Value.Bool(true) => "TRUE",
                Value.Bool(false) => "FALSE",
                _ => null
            }
            : null;
}
