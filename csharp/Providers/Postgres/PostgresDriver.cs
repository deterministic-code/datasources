using System.Text.RegularExpressions;
using Datasources;

namespace Datasources.Postgres;

public sealed class PostgresDriver : IDriver
{
    static readonly StatementTextRenderer Statements =
        new(t => new PostgresStatementRenderer(t));
    static readonly DeterministicTypeConverter Types = new(
        new Dictionary<string, string>
        {
            ["string"] = "TEXT",
            ["character"] = "CHAR(1)",
            ["number"] = "INTEGER",
            ["integer"] = "INTEGER",
            ["unsignedinteger"] = "BIGINT",
            ["smallinteger"] = "SMALLINT",
            ["unsignedsmallinteger"] = "INTEGER",
            ["biginteger"] = "BIGINT",
            ["unsignedbiginteger"] = "NUMERIC(20)",
            ["float"] = "DOUBLE PRECISION",
            ["decimal"] = "NUMERIC",
            ["boolean"] = "BOOLEAN",
            ["datetime"] = "TIMESTAMPTZ",
            ["binary"] = "BYTEA",
            ["uuid"] = "UUID",
            ["reference"] = "INTEGER",
        },
        new SpecFieldRules
        {
            DialectName = "postgres",
            StringUnlimited = "TEXT",
            StringSized = n => $"VARCHAR({n})",
            Character = "CHAR",
            Decimal = new DecimalRule.Optional("NUMERIC", "NUMERIC"),
        });
    static readonly DefaultValueConverter Defaults = new(new DefaultValueOptions
    {
        NewId = () => "gen_random_uuid()",
        Now = () => "LOCALTIMESTAMP",
        UtcNow = () => "(NOW() AT TIME ZONE 'UTC')",
        BooleanOn = "TRUE",
        BooleanOff = "FALSE",
        Hex = arg => $"'\\x{arg}'",
        HexReverse = new Regex(@"^'\\x(.*)'$"),
    });

    public string QuoteLeft => "\"";
    public string QuoteRight => "\"";
    public IMapping<string, string>? TypeConverter => Types;
    public DefaultValueConverter? DefaultValueConverter => Defaults;
    public StatementTextRenderer? StatementRenderer => Statements;
    public Information? Information { get; } = new(
        [
            "PostgreSQL server driver.",
            "Full connection, command, transaction, and repository support.",
        ],
        [
            "Overrides SelectInsertedIdStatement to SELECT setval(pg_get_serial_sequence('{table}', '{column}'), MAX(\"{column}\")) AS {column}",
            "Overrides CreateTableStatement identity to GENERATED BY DEFAULT AS IDENTITY",
            "Overrides CreateTableStatement boolean defaults (0/1 → TRUE/FALSE)",
            "Overrides CreateTableStatement type mapping (int→INTEGER, uuid→UUID, string→TEXT, bool→BOOLEAN, decimal→NUMERIC, float→DOUBLE PRECISION, datetime→TIMESTAMPTZ, binary→BYTEA)",
            "Overrides CreateCreateStoredProcedureStatement to PROCEDURE Create{Plural}",
            "Overrides CreateReadStoredProcedureStatement to PROCEDURE Read{Plural}By{Properties}",
            "Overrides CreateUpdateStoredProcedureStatement to PROCEDURE Update{Plural}By{Properties}",
            "Overrides CreateDeleteStoredProcedureStatement to PROCEDURE Delete{Plural}By{Properties}",
            "Overrides CreateBulkCreateStoredProcedureStatement to PROCEDURE BulkCreate{Plural}",
            "Overrides CreateBulkUpdateStoredProcedureStatement to PROCEDURE BulkUpdate{Plural}",
            "Overrides CreateBulkDeleteStoredProcedureStatement to PROCEDURE BulkDelete{Plural}",
        ],
        []);
    public IConnection Connection(IReadOnlyDictionary<string, string?>? options) => new PostgresConnection(options);
    public ICommand Command(IConnection connection) =>
        new PostgresCommand((PostgresConnection)connection, Statements);
    public ITransaction Transaction(IConnection connection, IsolationLevel isolation = IsolationLevel.ReadCommitted) =>
        new PostgresTransaction((PostgresConnection)connection, isolation);
    public IReadOnlyDictionary<string, TypeConverter<Value, Value>> RowTypeConverters => PostgresRowTypeConverters.All;

    internal static readonly IReadOnlyDictionary<string, string> ColumnTypes =
        new Dictionary<string, string>
        {
            ["int"] = "INTEGER",
            ["uuid"] = "UUID",
            ["string"] = "TEXT",
            ["bool"] = "BOOLEAN",
            ["decimal"] = "NUMERIC",
            ["float"] = "DOUBLE PRECISION",
            ["datetime"] = "TIMESTAMPTZ",
            ["binary"] = "BYTEA",
        };

    public string ColumnType(string name) =>
        ColumnTypes.TryGetValue(name, out var sql) ? sql : throw new DatasourceException($"Unknown postgres type \"{name}\"");
}
