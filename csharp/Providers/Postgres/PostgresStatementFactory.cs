namespace Datasources.Postgres;

internal sealed class PostgresStatementFactory : CreateTableStatementRenderer
{
    protected override string Type(Column column) => column.Type switch
    {
        "int" or "uuid" or "string" or "datetime" or "bool" or "decimal" or "float" or "binary"
            => new PostgresDriver().ColumnType(column.Type),
        _ => column.Type
    };

    protected override string Default(Column column) =>
        column.Type == "bool" && column.Default is { Value: "1" } value
            ? base.Default(column with { Default = value with { Value = "TRUE" } })
            : base.Default(column);

    protected override string Identity(Column column) =>
        column.Identity ? " GENERATED BY DEFAULT AS IDENTITY" : "";

    public IStatement Transform(IStatement statement) => statement switch
    {
        CreateTableStatement { Table: not null } create => new CreateTableStatement(Render(create)),
        InsertedIdStatement inserted => new SelectStatement($"SELECT lastval() AS {inserted.Column}"),
        _ => statement
    };
}
