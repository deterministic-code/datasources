using Datasources;
using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace Datasources.SqlSpecs;

public static class SchemaSpec
{
    public static IReadOnlyList<CreateTableStatement> Tables(
        string name,
        string provider,
        Func<string, string> quote,
        Func<string, string> columnType,
        IReadOnlyDictionary<string, string>? rename = null,
        bool executableText = false) =>
        Load(name).Select(table => Statement(table, provider, quote, columnType, rename, executableText)).ToArray();

    public static string Sql(
        string name,
        string provider,
        Func<string, string> quote,
        Func<string, string> columnType,
        IReadOnlyDictionary<string, string>? rename = null) =>
        string.Join(";\n", Tables(name, provider, quote, columnType, rename, true).Select(statement => statement.GetText()));

    public static string ColumnType(string provider, string canonical) => provider switch
    {
        "sqlite" => canonical switch
        {
            "int" or "bool" => "INTEGER",
            "uuid" or "string" or "datetime" => "TEXT",
            "decimal" => "NUMERIC",
            "float" => "REAL",
            "binary" => "BLOB",
            _ => throw new InvalidOperationException($"Unknown sqlite type \"{canonical}\"")
        },
        "mysql" => canonical switch
        {
            "int" => "INT",
            "uuid" => "CHAR(36)",
            "string" or "datetime" => "TEXT",
            "bool" => "TINYINT",
            "decimal" => "DECIMAL(18,4)",
            "float" => "DOUBLE",
            "binary" => "BLOB",
            _ => throw new InvalidOperationException($"Unknown mysql type \"{canonical}\"")
        },
        "postgres" => canonical switch
        {
            "int" => "INTEGER",
            "uuid" => "UUID",
            "string" => "TEXT",
            "bool" => "BOOLEAN",
            "decimal" => "NUMERIC",
            "float" => "DOUBLE PRECISION",
            "datetime" => "TIMESTAMPTZ",
            "binary" => "BYTEA",
            _ => throw new InvalidOperationException($"Unknown postgres type \"{canonical}\"")
        },
        _ => throw new InvalidOperationException($"unknown provider {provider}")
    };

    static CreateTableStatement Statement(
        TableSpec table,
        string provider,
        Func<string, string> quote,
        Func<string, string> columnType,
        IReadOnlyDictionary<string, string>? rename,
        bool executableText)
    {
        if (provider is not ("sqlite" or "mysql" or "postgres"))
            throw new InvalidOperationException($"unknown provider {provider}");
        var columns = Columns(table);
        var keys = columns.Where(column => column.PrimaryKey).Select(column => column.Name).ToArray();
        var inline = keys.Length > 0 && (provider == "sqlite" || (executableText && keys.All(key => columns.First(column => column.Name == key).Type == "int")));
        var constraints = new List<ITableConstraint>();
        if (keys.Length > 0 && !inline)
            constraints.Add(new PrimaryKey($"pk_{Name(table.Name, rename)}", keys.Select(quote).ToArray()));
        constraints.AddRange((table.Constraints ?? []).Select(constraint => Constraint(constraint, quote, rename)));
        return new CreateTableStatement(
            quote(Name(table.Name, rename)),
            columns.Select(column => Column(column, provider, quote, columnType, executableText, inline)).ToArray(),
            constraints);
    }

    static Column Column(
        ColumnSpec column,
        string provider,
        Func<string, string> quote,
        Func<string, string> columnType,
        bool executableText,
        bool inline)
    {
        var type = executableText || provider == "sqlite" ? columnType(column.Type) : column.Type;
        if (inline && column.PrimaryKey)
            type += provider switch
            {
                "mysql" => " PRIMARY KEY AUTO_INCREMENT",
                "postgres" => " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                _ => " PRIMARY KEY"
            };
        return new Column(
            quote(column.Name),
            type,
            column.Default is null ? null : new ColumnDefault(column.Default),
            column.NotNull ? new NotNull() : null,
            !executableText && provider != "sqlite" && column.PrimaryKey && column.Type == "int");
    }

    static ITableConstraint Constraint(ConstraintSpec constraint, Func<string, string> quote, IReadOnlyDictionary<string, string>? rename) =>
        constraint.Kind switch
        {
            "primaryKey" => new PrimaryKey(constraint.Name, constraint.Columns.Select(quote).ToArray()),
            "unique" => new UniqueConstraint(constraint.Name, constraint.Columns.Select(quote).ToArray()),
            "check" => new CheckConstraint(constraint.Name, constraint.Expression ?? throw new InvalidOperationException($"{constraint.Name}: empty check")),
            "foreignKey" => new ForeignKey(
                constraint.Name,
                constraint.Columns.Select(quote).ToArray(),
                quote(Name(constraint.References ?? throw new InvalidOperationException($"{constraint.Name}: empty references"), rename)),
                (constraint.ReferencesColumns ?? []).Select(quote).ToArray(),
                Action(constraint.OnDelete),
                Action(constraint.OnUpdate)),
            _ => throw new InvalidOperationException($"{constraint.Name}: empty constraint")
        };

    static ReferentialAction? Action(string? name) => name switch
    {
        null or "" => null,
        "cascade" => ReferentialAction.Cascade,
        "setNull" => ReferentialAction.SetNull,
        "setDefault" => ReferentialAction.SetDefault,
        "restrict" => ReferentialAction.Restrict,
        "noAction" => ReferentialAction.NoAction,
        _ => throw new InvalidOperationException($"unknown referential action {name}")
    };

    static string Name(string logical, IReadOnlyDictionary<string, string>? rename) =>
        rename is not null && rename.TryGetValue(logical, out var physical) ? physical : logical;

    static List<ColumnSpec> Columns(TableSpec table)
    {
        var catalog = Catalog();
        var columns = new List<ColumnSpec>();
        foreach (var fragment in table.Use ?? [])
            columns.AddRange(catalog.Fragments.TryGetValue(fragment, out var found)
                ? found
                : throw new InvalidOperationException($"unknown fragment {fragment}"));
        columns.AddRange(table.Columns ?? []);
        return columns;
    }

    static IReadOnlyList<TableSpec> Load(string name)
    {
        var catalog = Catalog();
        return catalog.Schemas.TryGetValue(name, out var tables)
            ? tables
            : throw new InvalidOperationException($"unknown schema {name}");
    }

    static CatalogFile Catalog() => cache ??= new DeserializerBuilder()
        .WithNamingConvention(CamelCaseNamingConvention.Instance)
        .Build()
        .Deserialize<CatalogFile>(File.ReadAllText(Path.Combine(SpecsDir(), "schemas.yaml")));

    static string SpecsDir()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
            if (File.Exists(Path.Combine(dir.FullName, "specs", "command-crud.yaml")))
                return Path.Combine(dir.FullName, "specs");
        throw new DirectoryNotFoundException("specs");
    }

    static CatalogFile? cache;

    sealed class CatalogFile
    {
        public Dictionary<string, List<ColumnSpec>> Fragments { get; set; } = [];
        public Dictionary<string, List<TableSpec>> Schemas { get; set; } = [];
    }

    sealed class TableSpec
    {
        public string Name { get; set; } = "";
        public List<string>? Use { get; set; }
        public List<ColumnSpec>? Columns { get; set; }
        public List<ConstraintSpec>? Constraints { get; set; }
    }

    sealed class ColumnSpec
    {
        public string Name { get; set; } = "";
        public string Type { get; set; } = "";
        public bool PrimaryKey { get; set; }
        public bool NotNull { get; set; }
        public string? Default { get; set; }
    }

    sealed class ConstraintSpec
    {
        public string Kind { get; set; } = "";
        public string Name { get; set; } = "";
        public List<string> Columns { get; set; } = [];
        public string? References { get; set; }
        public List<string>? ReferencesColumns { get; set; }
        public string? OnDelete { get; set; }
        public string? OnUpdate { get; set; }
        public string? Expression { get; set; }
    }
}
