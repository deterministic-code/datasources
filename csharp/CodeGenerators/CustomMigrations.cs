using System.Text.RegularExpressions;

namespace Datasources.CodeGenerators;

public static class CustomMigrations
{
    static readonly Regex Filename = new(@"^(\d+)_([A-Za-z0-9][A-Za-z0-9_-]*)_(up|down)\.sql$", RegexOptions.Compiled);

    public static IReadOnlyList<GenerateEntry> Of(
        IReadOnlyDictionary<string, string> files,
        string dialect,
        string? deterministicDir)
    {
        if (string.IsNullOrEmpty(deterministicDir)) return [];
        var prefix = $"{deterministicDir.TrimEnd('/', '\\')}/custom/{dialect}/";
        var alt = $"custom/{dialect}/";
        var slots = new Dictionary<string, Slot>(StringComparer.Ordinal);
        foreach (var (path, content) in files)
        {
            var rel = path.StartsWith(prefix, StringComparison.Ordinal) ? path[prefix.Length..]
                : path.StartsWith(alt, StringComparison.Ordinal) ? path[alt.Length..]
                : null;
            if (rel is null || rel.Contains('/') || rel.Contains('\\')) continue;
            var match = Filename.Match(rel);
            if (!match.Success)
                throw new InvalidOperationException(
                    $"discoverCustomMigrations: {path} does not match expected pattern <order>_<name>_(up|down).sql");
            var order = int.Parse(match.Groups[1].Value);
            if (order is < 1 or > 999)
                throw new InvalidOperationException(
                    $"discoverCustomMigrations: {path} has order {order}; must be in [1, 999]");
            var name = match.Groups[2].Value;
            var side = match.Groups[3].Value;
            var key = $"{order}|{name}";
            if (!slots.TryGetValue(key, out var slot)) slots[key] = slot = new Slot(order, name);
            if (side == "up")
            {
                if (slot.Up is not null)
                    throw new InvalidOperationException($"discoverCustomMigrations: duplicate up file for order={order} name={name}");
                slot.Up = content;
            }
            else
            {
                if (slot.Down is not null)
                    throw new InvalidOperationException($"discoverCustomMigrations: duplicate down file for order={order} name={name}");
                slot.Down = content;
            }
        }
        var missing = slots.Values
            .SelectMany(slot =>
            {
                var list = new List<string>();
                if (slot.Up is null) list.Add($"missing _up.sql counterpart for {slot.Name}");
                if (slot.Down is null) list.Add($"missing _down.sql counterpart for {slot.Name}");
                return list;
            })
            .ToList();
        if (missing.Count > 0)
            throw new InvalidOperationException($"discoverCustomMigrations: {missing.Count} mismatched up/down pair(s):\n  {string.Join("\n  ", missing)}");
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var entries = new List<GenerateEntry>();
        foreach (var slot in slots.Values.OrderBy(s => s.Order).ThenBy(s => s.Name, StringComparer.Ordinal))
        {
            foreach (var (side, body) in new[] { ("up", slot.Up!), ("down", slot.Down!) })
            {
                var filename = $"{slot.Order:D10}_custom_{slot.Order:D3}_{slot.Name}_{side}.sql";
                if (!seen.Add(filename))
                    throw new InvalidOperationException(
                        $"custom migration filename collision for dialect '{dialect}': {filename} is generated by both an included datasource and this project");
                entries.Add(new($"{dialect}/migrations/{filename}", body));
            }
        }
        return entries;
    }

    sealed class Slot(int order, string name)
    {
        public int Order { get; } = order;
        public string Name { get; } = name;
        public string? Up { get; set; }
        public string? Down { get; set; }
    }
}
