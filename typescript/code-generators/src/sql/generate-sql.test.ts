import assert from "node:assert/strict";
import { describe, it } from "vitest";
import { parse, stringify } from "yaml";
import { memoryReader } from "@deterministic-code/generators-common/deterministic-reader";
import { generate as generateSql } from "./generate-sql.ts";
import { generate as generateStoredProcedures } from "./generate-stored-procedures.ts";

const TYPES_YAML = `types:
  - user:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
        - created:
            type: datetime
        - updated:
            type: datetime
`;

const ctx = (settings: Record<string, string>) => ({
  reader: memoryReader({ "types.yaml": TYPES_YAML }),
  settings,
});

const names = (
  entries: { filename: string }[],
): string[] => entries.map((e) => e.filename).sort();

const body = (entry: { content?: string; contents?: string } | undefined): string =>
  entry === undefined ? "" : "contents" in entry && entry.contents !== undefined ? String(entry.contents) : String(entry.content ?? "");

const postgresOn = {
  "datasource.use_stored_procedures": "true",
};

describe("generate-sql datasource.use_stored_procedures", () => {
  it("emits stored-procedure migrations when the flag is true on postgres", async () => {
    const files = names(await generateSql(ctx(postgresOn), ["postgres"]));
    assert.ok(files.includes("postgres/migrations/0001_initial_up.sql"));
    assert.ok(
      files.includes("postgres/migrations/0002_stored_procedures_up.sql"),
    );
    assert.ok(
      files.includes("postgres/migrations/0002_stored_procedures_down.sql"),
    );
  });

  it("omits stored-procedure migrations when the flag is absent", async () => {
    const files = names(
      await generateSql(ctx({}), ["postgres"]),
    );
    assert.ok(files.includes("postgres/migrations/0001_initial_up.sql"));
    assert.equal(
      files.some((f) => f.includes("stored_procedures")),
      false,
    );
  });

  it("omits stored-procedure migrations on sqlite even when the flag is true", async () => {
    const files = names(
      await generateSql(
        ctx({ "datasource.use_stored_procedures": "true" }),
        ["sqlite"],
      ),
    );
    assert.ok(files.includes("sqlite/migrations/0001_initial_up.sql"));
    assert.equal(
      files.some((f) => f.includes("stored_procedures")),
      false,
    );
  });
});

const identityYaml = `types:
  - person:
      tags: [datasource_type]
      inherits: set
      fields:
        - code:
            type: integer
        - email:
            type: string
  - link:
      tags: [datasource_type]
      inherits: set
      ids: [left_id, right_id]
      fields:
        - left_id:
            type: integer
        - right_id:
            type: integer
  - country:
      tags: [datasource_type]
      inherits: set
      fields:
        - name:
            type: string
`;

const identityDatasource = `includes:
  - types:
      filter: tag == "datasource_type"
types:
  - country:
      fields:
        - id:
            is_fixed_id: true
            is_readonly: true
`;

const identityCtx = {
  reader: memoryReader({
    "types.yaml": identityYaml,
    "datasource.yaml": identityDatasource,
  }),
  settings: {},
};

const upBody = async (
  settings: Record<string, string> = {},
) => {
  const files = await generateSql({
    reader: identityCtx.reader,
    settings,
  }, ["postgres"]);
  const up = files.find((e) => e.filename.endsWith("0001_initial_up.sql"));
  assert.ok(up, "expected initial up migration");
  return "contents" in up ? String(up.contents) : up.content;
};

describe("generate-sql identity keys", () => {
  it("uses the injected set id as a generated primary key", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "people"/);
    assert.match(sql, /"id" INTEGER GENERATED BY DEFAULT AS IDENTITY/);
    assert.match(sql, /CONSTRAINT "people_primary_key" PRIMARY KEY/);
    assert.match(sql, /"code" INTEGER NOT NULL/);
    assert.match(sql, /"email"/);
  });

  it("emits a composite primary key when ids lists multiple columns", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "links"/);
    assert.match(sql, /"left_id" INTEGER NOT NULL/);
    assert.match(sql, /"right_id" INTEGER NOT NULL/);
    assert.match(
      sql,
      /CONSTRAINT "links_primary_key" PRIMARY KEY \("left_id", "right_id"\)/,
    );
    assert.doesNotMatch(sql, /CREATE TABLE "links"[\s\S]*GENERATED BY DEFAULT AS IDENTITY/);
  });

  it("emits a plain primary key when is_fixed_id is set", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "countries"/);
    assert.match(sql, /"id" INTEGER NOT NULL/);
    assert.match(sql, /CONSTRAINT "countries_primary_key" PRIMARY KEY \("id"\)/);
    assert.doesNotMatch(sql, /CREATE TABLE "countries"[\s\S]*GENERATED BY DEFAULT AS IDENTITY/);
  });
});

describe("generate-sql collection fields", () => {
  it("omits view collections from table columns and keeps the child FK", async () => {
    const files = await generateSql({
      reader: memoryReader({
        "types.yaml": `types:
  - contact:
      tags: [datasource_type, view_type]
      inherits: set
      fields:
        - email:
            type: string
        - addresses:
            type: address[]
            references: address.contact_id
  - address:
      tags: [datasource_type, view_type]
      inherits: set
      fields:
        - contact_id:
            type: number
            references: contact.id
        - city:
            type: string
`,
      }),
      settings: {},
    }, ["sqlite"]);
    const up = files.find((e) => e.filename.endsWith("0001_initial_up.sql"));
    assert.ok(up, "expected initial up migration");
    const sql = "contents" in up ? String(up.contents) : up.content;
    assert.match(sql, /CREATE TABLE "contacts"/);
    assert.match(sql, /CREATE TABLE "addresses"/);
    const contacts = sql.match(/CREATE TABLE "contacts" \(([\s\S]*?)\);/)?.[1];
    assert.ok(contacts, "expected contacts table body");
    assert.match(contacts, /"email"/);
    assert.doesNotMatch(contacts, /"addresses"/);
    assert.match(sql, /"contact_id"/);
    assert.match(sql, /FOREIGN KEY \("contact_id"\) REFERENCES "contacts"/);
  });

  it("emits a dictionary table with unique owner and key, flattening object values", async () => {
    const files = await generateSql({
      reader: memoryReader({
        "types.yaml": `types:
  - contact:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
  - locale_preferences:
      tags: [view_type]
      fields:
        - locale:
            type: string
        - timezone:
            type: string
  - contact_settings:
      tags: [datasource_type]
      inherits: set
      fields:
        - contact_id:
            type: integer
            references: contact.id
        - key:
            type: string
        - value:
            type: string
  - contact_preferences:
      tags: [datasource_type]
      inherits: set
      fields:
        - contact_id:
            type: integer
            references: contact.id
        - key:
            type: string
        - locale:
            type: string
        - timezone:
            type: string
  - contact_settings_map:
      tags: [view_type]
      inherits: dictionary
      fields:
        - key:
            type: string
        - value:
            type: string
  - contact_preferences_map:
      tags: [view_type]
      inherits: dictionary
      fields:
        - key:
            type: string
        - value:
            type: locale_preferences
  - contact_view:
      tags: [view_type]
      inherits: contact
      fields:
        - settings:
            type: contact_settings_map{}
            references: contact_settings.contact_id
        - prefs:
            type: contact_preferences_map{}
            references: contact_preferences.contact_id
  - phone:
      tags: [datasource_type]
      inherits: set
  - phone_attribute:
      tags: [datasource_type]
      inherits: set
      fields:
        - phone_id:
            type: integer
            references: phone.id
        - attribute_name:
            type: string
        - attribute_value:
            type: string
  - phone_attribute_map:
      tags: [view_type]
      inherits: dictionary
      fields:
        - key:
            type: string
            references: phone_attribute.attribute_name
        - value:
            type: string
            references: phone_attribute.attribute_value
  - phone_view:
      tags: [view_type]
      inherits: phone
      fields:
        - attributes:
            type: phone_attribute_map{}
            references: phone_attribute.phone_id
  - card_labels:
      tags: [view_type]
      inherits: dictionary
      fields:
        - key:
            type: string
        - value:
            type: string
`,
      }),
      settings: {},
    }, ["sqlite"]);
    const up = files.find((e) => e.filename.endsWith("0001_initial_up.sql"));
    assert.ok(up, "expected initial up migration");
    const sql = "contents" in up ? String(up.contents) : up.content;
    assert.match(sql, /CREATE TABLE "contact_settings"/);
    assert.match(sql, /CREATE TABLE "contact_preferences"/);
    assert.doesNotMatch(sql, /CREATE TABLE "card_labels"/);
    const settings = sql.match(
      /CREATE TABLE "contact_settings" \(([\s\S]*?)\);/,
    )?.[1];
    assert.ok(settings, "expected contact_settings table body");
    assert.match(settings, /"contact_id"/);
    assert.match(settings, /"key"/);
    assert.match(settings, /"value"/);
    assert.match(settings, /"id"/);
    const prefs = sql.match(/CREATE TABLE "contact_preferences" \(([\s\S]*?)\);/)?.[1];
    assert.ok(prefs, "expected contact_preferences table body");
    assert.match(prefs, /"locale"/);
    assert.match(prefs, /"timezone"/);
    assert.doesNotMatch(prefs, /"value"/);
    assert.match(sql, /CREATE UNIQUE INDEX .* ON "contact_settings"/);
    assert.match(sql, /CREATE UNIQUE INDEX .* ON "contact_preferences"/);
    assert.match(sql, /CREATE UNIQUE INDEX .* ON "phone_attributes".*"phone_id".*"attribute_name"/);
  });
});

describe("generate-stored-procedures datasource.use_stored_procedures", () => {
  it("emits procedure migrations when the flag is true", async () => {
    const files = names(await generateStoredProcedures(ctx(postgresOn), ["postgres"]));
    assert.deepEqual(files, [
      "postgres/migrations/0002_stored_procedures_down.sql",
      "postgres/migrations/0002_stored_procedures_up.sql",
    ]);
    const up = body(
      (await generateStoredProcedures(ctx(postgresOn), ["postgres"])).find((entry) =>
        entry.filename.endsWith("_stored_procedures_up.sql"),
      ),
    );
    assert.ok(up.includes("read_users"));
    assert.ok(up.includes("bulk_create_users"));
    assert.ok(up.includes("CREATE OR REPLACE"));
  });

  it("emits nothing when the flag is absent", async () => {
    const files = await generateStoredProcedures(ctx({}), ["postgres"]);
    assert.deepEqual(files, []);
  });
});

describe("generate-sql version diffs", () => {
  it("emits numbered up/down files from frozen diffs", async () => {
    const path = "version-20261016T000000Z-001/diff.yaml";
    const diff = stringify({
      "types.yaml": { added: true, content: parse(TYPES_YAML) },
    });
    const files = names(
      await generateSql(
        {
          reader: memoryReader({ "types.yaml": TYPES_YAML, [path]: diff }),
          settings: { "version.diffs": path },
        },
        ["sqlite"],
      ),
    );
    assert.deepEqual(files, ["sqlite/migrations/0001_down.sql", "sqlite/migrations/0001_up.sql"]);
  });

  it("replaces stored procedures when a later version adds a column", async () => {
    const first = "version-20261016T000000Z-001/diff.yaml";
    const second = "version-20261016T000000Z-002/diff.yaml";
    const nextYaml = `types:
  - user:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
        - created:
            type: datetime
        - updated:
            type: datetime
        - notes:
            type: string
`;
    const entries = await generateSql(
      {
        reader: memoryReader({
          "types.yaml": nextYaml,
          [first]: stringify({ "types.yaml": { added: true, content: parse(TYPES_YAML) } }),
          [second]: stringify({ "types.yaml": parse(nextYaml) }),
        }),
        settings: {
          "version.diffs": `${first}\n${second}`,
          "datasource.use_stored_procedures": "true",
        },
      },
      ["postgres"],
    );
    const up2 = body(entries.find((entry) => entry.filename === "postgres/migrations/0002_up.sql"));
    const down2 = body(entries.find((entry) => entry.filename === "postgres/migrations/0002_down.sql"));
    assert.ok(up2.includes("notes"));
    assert.ok(up2.includes("CREATE OR REPLACE"));
    assert.ok(down2.includes("CREATE OR REPLACE"));
  });

  it("throws when live yaml drifted from frozen diffs", async () => {
    const path = "version-20261016T000000Z-001/diff.yaml";
    const diff = stringify({
      "types.yaml": { added: true, content: parse(TYPES_YAML) },
    });
    await assert.rejects(
      () =>
        generateSql(
          {
            reader: memoryReader({
              "types.yaml": `types:
  - extra:
      tags: [datasource_type]
      inherits: set
      fields:
        - name:
            type: string
`,
              [path]: diff,
            }),
            settings: { "version.diffs": path },
          },
          ["sqlite"],
        ),
      /run datasources version first/,
    );
  });
});
