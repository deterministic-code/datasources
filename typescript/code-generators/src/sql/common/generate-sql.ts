const finalizeSql = (text: string, casing: PackCasing): string => {
  const out = casing.applyKeywords(text.replace(/\n{3,}/g, "\n\n"));
  return out.endsWith("\n") ? out : `${out}\n`;
};

const flattenTable = (
  dialect: SqlDialect,
  table: LiveTable,
  mapping: SqlMapping,
  separator: string,
): string => {
  const indexes = table.indexes.map((idx) =>
    renderSql(dialect, createIndexStatementOf(dialect, mapping, table, idx)),
  );
  const live = { ...table, pkName: pkName(table, overlayOf(table)) };
  const audit = hasAuditColumns(table)
    ? renderSql(
        dialect,
        createTriggerStatementOf(dialect, live, mapping, live.pkName ?? "id"),
      )
    : "";
  return joinBatches(
    [renderSql(dialect, createTableStatementOf(dialect, table, mapping)), ...indexes, audit],
    separator,
  );
};

const generateInitialMigration = (
  language: string,
  types: SqlTable[],
  seedsByTable: Map<string, SeedRow[]>,
  casing: PackCasing,
  settings: Record<string, string>,
): { up: SqlFile; down: SqlFile } => {
  const dialect = requireDialect(language);
  const mapping = new SqlMapping(casing, types);
  const live = buildLiveTables(types, mapping);
  const separator = batchSeparatorOf(settings);
  const seeds = seedSections(dialect, live, seedsByTable, mapping);

  return {
    up: {
      path: "0001_initial_up.sql",
      content: finalizeSql(
        fill(migrationUpTmpl, {
          dialect,
          preamble: "",
          body: joinBatches(
            [
              ...live.map((t) => flattenTable(dialect, t, mapping, separator)),
              ...(seeds.length === 0 ? [] : [`-- Seed data\n${joinBatches(seeds, separator)}`]),
            ],
            separator,
          ),
        }),
        casing,
      ),
    },
    down: {
      path: "0001_initial_down.sql",
      content: finalizeSql(
        fill(migrationDownTmpl, {
          dialect,
          dropStatements: joinBatches(
            [...live]
              .reverse()
              .map((t) => renderSql(dialect, dropTableStatementOf(dialect, t.tableName))),
            separator,
          ),
        }),
        casing,
      ),
    },
  };
};

const customEntries = async (
  dialect: string,
  deterministicDir: string | undefined,
): Promise<GenerateEntry[]> => {
  if (!deterministicDir) return [];
  const files = await buildCustomMigrationFiles(deterministicDir, dialect);
  const seen = new Set<string>();
  for (const { filename } of files) {
    if (seen.has(filename)) {
      throw new Error(
        `custom migration filename collision for dialect '${dialect}': ${filename} is generated by both an included datasource and this project`,
      );
    }
    seen.add(filename);
  }
  return files.map((file) =>
    content(`${dialect}/migrations/${file.filename}`, file.content),
  );
};

const loadSchema = async (
  ctx: GenerateContext,
): Promise<{
  types: SqlTable[];
  seeds: Map<string, SeedRow[]>;
}> => {
  const spec = await DeterministicParser(ctx.reader).parse(ctx.settings);
  return {
    types: sqlTablesFrom(spec),
    seeds: spec.datasourceSeeds,
  };
};

/** DDL initial migration (+ optional custom migrations and stored procedures) for one SQL dialect. */
const readerFor = async (dialect: string, ctx: GenerateContext): Promise<GenerateContext> => {
  const named = `datasource.${dialect}.yaml`;
  if (!(await ctx.reader.exists(named))) return ctx;
  const yaml = await ctx.reader.read(named);
  return {
    ...ctx,
    reader: {
      read: (name) => (name === "datasource.yaml" ? Promise.resolve(yaml) : ctx.reader.read(name)),
      exists: (name) => (name === "datasource.yaml" ? Promise.resolve(true) : ctx.reader.exists(name)),
    },
  };
};

export const generateSqlFor = async (
  dialect: SqlDialect,
  ctx: GenerateContext,
): Promise<GenerateEntry[]> => {
  const key = requireDialect(dialect);
  const scoped = await readerFor(key, ctx);
  const casing = createCasing(scoped.settings);
  const dir = scoped.settings["paths.deterministic"];
  const schema = await schemaFiles(key, scoped, casing);
  return [
    ...schema.entries,
    ...(await customEntries(key, dir)),
    ...(await generateProceduresForDialect(dialect, scoped, schema.count + 1)),
  ];
};

const schemaFiles = async (
  key: SqlDialect,
  ctx: GenerateContext,
  casing: PackCasing,
): Promise<{ entries: GenerateEntry[]; count: number }> => {
  if (versionDiffPaths(ctx.settings).length > 0) {
    const liveTypes = (await ctx.reader.exists("types.yaml"))
      ? await ctx.reader.read("types.yaml")
      : undefined;
    const liveDatasource = (await ctx.reader.exists("datasource.yaml"))
      ? await ctx.reader.read("datasource.yaml")
      : undefined;
    const versions = await versionMigrationFiles(key, ctx, casing, {
      typesYaml: liveTypes,
      datasourceYaml: liveDatasource,
    });
    return {
      entries: versions.files.map((file) =>
        content(`${key}/migrations/${file.path}`, file.content),
      ),
      count: versions.count,
    };
  }
  const data = await loadSchema(ctx);
  const initial = generateInitialMigration(key, data.types, data.seeds, casing, ctx.settings);
  return {
    entries: [
      content(`${key}/migrations/${initial.up.path}`, initial.up.content),
      content(`${key}/migrations/${initial.down.path}`, initial.down.content),
    ],
    count: 1,
  };
};
