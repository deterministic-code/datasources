import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import {
  CheckConstraint,
  ColumnDefault,
  CreateTableStatement,
  ForeignKey,
  NotNull,
  PrimaryKey,
  ReferentialAction,
  UniqueConstraint,
  type Column,
  type ITableConstraint,
  type ReferentialActionName,
} from "@datasources/core";

type ColumnSpec = {
  name: string;
  type: string;
  primaryKey?: boolean;
  notNull?: boolean;
  default?: string;
};

type ConstraintSpec = {
  kind: string;
  name: string;
  columns?: string[];
  references?: string;
  referencesColumns?: string[];
  onDelete?: string;
  onUpdate?: string;
  expression?: string;
};

type TableSpec = {
  name: string;
  use?: string[];
  columns?: ColumnSpec[];
  constraints?: ConstraintSpec[];
};

type CatalogFile = {
  fragments: Record<string, ColumnSpec[]>;
  schemas: Record<string, TableSpec[]>;
};

export const repoRoot = (from = fileURLToPath(import.meta.url)): string => {
  for (let dir = dirname(from); ; dir = dirname(dir)) {
    if (existsSync(join(dir, "specs", "command-crud.yaml"))) return dir;
    if (dir === dirname(dir)) throw new Error("specs not found");
  }
};

let cache: CatalogFile | undefined;

const file = (): CatalogFile =>
  (cache ??= parse(readFileSync(join(repoRoot(), "specs", "schemas.yaml"), "utf8")) as CatalogFile);

const physical = (logical: string, rename?: Readonly<Record<string, string>>): string =>
  rename?.[logical] ?? logical;

export const columnType = (provider: string, canonical: string): string => {
  const mapped = ({
    sqlite: {
      int: "INTEGER",
      bool: "INTEGER",
      uuid: "TEXT",
      string: "TEXT",
      datetime: "TEXT",
      decimal: "NUMERIC",
      float: "REAL",
      binary: "BLOB",
    },
    mysql: {
      int: "INT",
      uuid: "CHAR(36)",
      string: "TEXT",
      datetime: "TEXT",
      bool: "TINYINT",
      decimal: "DECIMAL(18,4)",
      float: "DOUBLE",
      binary: "BLOB",
    },
    postgres: {
      int: "INTEGER",
      uuid: "UUID",
      string: "TEXT",
      bool: "BOOLEAN",
      decimal: "NUMERIC",
      float: "DOUBLE PRECISION",
      datetime: "TIMESTAMPTZ",
      binary: "BYTEA",
    },
  } as Record<string, Record<string, string>>)[provider];
  const type = mapped?.[canonical];
  if (!type) throw new Error(mapped ? `Unknown ${provider} type "${canonical}"` : `unknown provider ${provider}`);
  return type;
};

const action = (name?: string): ReferentialActionName | undefined =>
  ({
    cascade: ReferentialAction.Cascade,
    setNull: ReferentialAction.SetNull,
    setDefault: ReferentialAction.SetDefault,
    restrict: ReferentialAction.Restrict,
    noAction: ReferentialAction.NoAction,
  }[name ?? ""] ?? (name ? (() => { throw new Error(`unknown referential action ${name}`); })() : undefined));

const columnsOf = (table: TableSpec): ColumnSpec[] => [
  ...(table.use ?? []).flatMap((fragment) => file().fragments[fragment] ?? (() => { throw new Error(`unknown fragment ${fragment}`); })()),
  ...(table.columns ?? []),
];

const constraintOf = (
  constraint: ConstraintSpec,
  quote: (id: string) => string,
  rename?: Readonly<Record<string, string>>,
): ITableConstraint => {
  const columns = (constraint.columns ?? []).map(quote);
  return ({
    primaryKey: () => new PrimaryKey(constraint.name, columns),
    unique: () => new UniqueConstraint(constraint.name, columns),
    check: () => new CheckConstraint(constraint.name, constraint.expression ?? (() => { throw new Error(`${constraint.name}: empty check`); })()),
    foreignKey: () => new ForeignKey(
      constraint.name,
      columns,
      quote(physical(constraint.references ?? (() => { throw new Error(`${constraint.name}: empty references`); })(), rename)),
      (constraint.referencesColumns ?? []).map(quote),
      action(constraint.onDelete),
      action(constraint.onUpdate),
    ),
  }[constraint.kind] ?? (() => { throw new Error(`${constraint.name}: empty constraint`); }))();
};

const columnOf = (
  column: ColumnSpec,
  provider: string,
  quote: (id: string) => string,
  mapType: (canonical: string) => string,
  executableText: boolean,
  inline: boolean,
): Column => {
  const mapped = executableText || provider === "sqlite" ? mapType(column.type) : column.type;
  const type = inline && column.primaryKey
    ? `${mapped}${({ mysql: " PRIMARY KEY AUTO_INCREMENT", postgres: " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" } as Record<string, string>)[provider] ?? " PRIMARY KEY"}`
    : mapped;
  return {
    name: quote(column.name),
    type,
    ...(column.default === undefined ? {} : { default: new ColumnDefault(column.default) }),
    ...(column.notNull ? { notNull: new NotNull() } : {}),
    ...( !executableText && provider !== "sqlite" && column.primaryKey && column.type === "int" ? { identity: true } : {}),
  };
};

const statementOf = (
  table: TableSpec,
  provider: string,
  quote: (id: string) => string,
  mapType: (canonical: string) => string,
  rename: Readonly<Record<string, string>> | undefined,
  executableText: boolean,
): CreateTableStatement => {
  if (provider !== "sqlite" && provider !== "mysql" && provider !== "postgres")
    throw new Error(`unknown provider ${provider}`);
  const columns = columnsOf(table);
  const keys = columns.filter((column) => column.primaryKey).map((column) => column.name);
  const inline = keys.length > 0 && (provider === "sqlite" || (executableText && keys.every((key) => columns.find((column) => column.name === key)?.type === "int")));
  const constraints: ITableConstraint[] = [
    ...(keys.length > 0 && !inline ? [new PrimaryKey(`pk_${physical(table.name, rename)}`, keys.map(quote))] : []),
    ...(table.constraints ?? []).map((constraint) => constraintOf(constraint, quote, rename)),
  ];
  return new CreateTableStatement(
    quote(physical(table.name, rename)),
    columns.map((column) => columnOf(column, provider, quote, mapType, executableText, inline)),
    constraints,
  );
};

export const tables = (
  name: string,
  provider: string,
  quote: (id: string) => string,
  mapType: (canonical: string) => string,
  rename?: Readonly<Record<string, string>>,
  executableText = false,
): CreateTableStatement[] => {
  const schemas = file().schemas[name];
  if (!schemas) throw new Error(`unknown schema ${name}`);
  return schemas.map((table) => statementOf(table, provider, quote, mapType, rename, executableText));
};

export const schemaSql = (
  name: string,
  provider: string,
  quote: (id: string) => string,
  mapType: (canonical: string) => string,
  rename?: Readonly<Record<string, string>>,
): string => tables(name, provider, quote, mapType, rename, true).map((statement) => statement.getText()).join(";\n");
