import {
  ColumnDefault,
  CreateTableStatement,
  DefaultStatementTextRenderer,
  ForeignKey,
  SelectInsertedIdStatement,
  NotNull,
  PrimaryKey,
  ReferentialAction,
  SelectStatement,
  StatementTextRenderer,
} from "@datasources/core";
import { describe, expect, it } from "vitest";
import { PostgresCreateTableStatementRenderer } from "./PostgresCreateTableStatementRenderer.ts";
import { PostgresStatementRenderer } from "./PostgresStatementRenderer.ts";

describe("PostgresStatementRenderer", () => {
  const renderer = new StatementTextRenderer(t => new PostgresStatementRenderer(t));

  it("renders inserted id and create table", () => {
    expect(renderer.render(new SelectInsertedIdStatement("users", "id"))).toBe(
      "SELECT lastval() AS id",
    );

    const create = new CreateTableStatement(
      "orders",
      [
        { name: "id", type: "INTEGER", default: new ColumnDefault("0", "df_id"), notNull: new NotNull("nn_id") },
        { name: "user_id", type: "INTEGER" },
      ],
      [
        new PrimaryKey("pk_orders", ["id"]),
        new ForeignKey("fk_orders_user", ["user_id"], "users", ["id"], ReferentialAction.Cascade),
      ],
    );
    expect(renderer.render(create)).toBe(new PostgresCreateTableStatementRenderer().render(create));
    expect(renderer.render(new SelectStatement({ table: "users", fields: ["id"] }))).toBe(
      "SELECT id FROM users",
    );
  });

  it("renders type default and identity", () => {
    const create = new CreateTableStatement("users", [
      { name: "id", type: "int", identity: true },
      { name: "is_enabled", type: "bool", default: new ColumnDefault("1") },
      { name: "is_disabled", type: "bool", default: new ColumnDefault("0", "df_off") },
      { name: "amount", type: "decimal", default: new ColumnDefault("1") },
      { name: "flag", type: "bool", default: new ColumnDefault("true") },
    ]);
    expect(renderer.render(create)).toBe(
      "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY, is_enabled BOOLEAN DEFAULT TRUE, is_disabled BOOLEAN CONSTRAINT df_off DEFAULT FALSE, amount NUMERIC DEFAULT 1, flag BOOLEAN DEFAULT true)",
    );
    expect(DefaultStatementTextRenderer.instance.render(create)).toBe(
      "CREATE TABLE users (id int, is_enabled bool DEFAULT 1, is_disabled bool CONSTRAINT df_off DEFAULT 0, amount decimal DEFAULT 1, flag bool DEFAULT true)",
    );
  });
});
