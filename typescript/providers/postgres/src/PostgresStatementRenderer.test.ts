import {
  AlterTableStatement,
  BulkUpdateStatement,
  type Cell,
  ColumnDefault,
  CreateBulkCreateStoredProcedureStatement,
  CreateBulkDeleteStoredProcedureStatement,
  CreateBulkUpdateStoredProcedureStatement,
  CreateCreateStoredProcedureStatement,
  CreateDeleteStoredProcedureStatement,
  CreateReadStoredProcedureStatement,
  CreateTableStatement,
  CreateUpdateStoredProcedureStatement,
  CreateTriggerStatement,
  DefaultStatementTextRenderer,
  DropRoutineStatement,
  DropTriggerStatement,
  ForeignKey,
  IdentityInsertStatement,
  InsertStatement,
  NotNull,
  PrimaryKey,
  ReferentialAction,
  SelectInsertedIdStatement,
  SelectStatement,
  StatementTextRenderer,
} from "@deterministic-code/datasources";
import { describe, expect, it } from "vitest";
import { PostgresCreateTableStatementRenderer } from "./PostgresCreateTableStatementRenderer.ts";
import { PostgresStatementRenderer } from "./PostgresStatementRenderer.ts";

describe("PostgresStatementRenderer", () => {
  const renderer = new StatementTextRenderer(t => new PostgresStatementRenderer(t));

  it("renders inserted id and create table", () => {
    expect(renderer.render(new SelectInsertedIdStatement("users", "id"))).toBe(
      "SELECT lastval() AS id",
    );

    const create = new CreateTableStatement(
      "orders",
      [
        { name: "id", type: "INTEGER", default: new ColumnDefault("0", "df_id"), notNull: new NotNull("nn_id") },
        { name: "user_id", type: "INTEGER" },
      ],
      [
        new PrimaryKey("pk_orders", ["id"]),
        new ForeignKey("fk_orders_user", ["user_id"], "users", ["id"], ReferentialAction.Cascade),
      ],
    );
    expect(renderer.render(create)).toBe(new PostgresCreateTableStatementRenderer().render(create));
    expect(renderer.render(new SelectStatement({ table: "users", fields: ["id"] }))).toBe(
      "SELECT id FROM users",
    );
  });

  it("renders type default and identity", () => {
    const create = new CreateTableStatement("users", [
      { name: "id", type: "int", identity: true },
      { name: "is_enabled", type: "bool", default: new ColumnDefault("1") },
      { name: "is_disabled", type: "bool", default: new ColumnDefault("0", "df_off") },
      { name: "amount", type: "decimal", default: new ColumnDefault("1") },
      { name: "flag", type: "bool", default: new ColumnDefault("true") },
    ]);
    expect(renderer.render(create)).toBe(
      "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY, is_enabled BOOLEAN DEFAULT TRUE, is_disabled BOOLEAN CONSTRAINT df_off DEFAULT FALSE, amount NUMERIC DEFAULT 1, flag BOOLEAN DEFAULT true)",
    );
    expect(DefaultStatementTextRenderer.instance.render(create)).toBe(
      "CREATE TABLE users (id int, is_enabled bool DEFAULT 1, is_disabled bool CONSTRAINT df_off DEFAULT 0, amount decimal DEFAULT 1, flag bool DEFAULT true)",
    );
  });

  it("renders bulk update with column types", () => {
    const update = new BulkUpdateStatement("parents", ["label"], ["id"], [
      { fields: [{ name: "label", value: "a" }], ids: [{ name: "id", value: 1 }] },
      { fields: [{ name: "label", value: "b" }], ids: [{ name: "id", value: 2 }] },
    ]);
    expect(renderer.render(update)).toBe(
      "UPDATE parents SET label = data.label FROM (SELECT $label__0::TEXT AS label, $id__0::INTEGER AS id UNION ALL SELECT $label__1::TEXT AS label, $id__1::INTEGER AS id) AS data WHERE parents.id = data.id",
    );
  });

  it("renders bulk update cell types", () => {
    const update = new BulkUpdateStatement("t", ["flag", "n", "at", "blob", "x"], ["id"], [
      {
        fields: [
          { name: "flag", value: true },
          { name: "n", value: 1.5 },
          { name: "at", value: new Date("2020-01-02T03:04:05.000Z") },
          { name: "blob", value: new Uint8Array([1]) },
          { name: "x", value: null },
        ] as { name: string; value: Cell }[],
        ids: [{ name: "id", value: 1n }],
      },
    ]);
    expect(renderer.render(update)).toBe(
      "UPDATE t SET flag = data.flag, n = data.n, at = data.at, blob = data.blob, x = data.x FROM (SELECT $flag__0::BOOLEAN AS flag, $n__0::DOUBLE PRECISION AS n, $at__0::TIMESTAMPTZ AS at, $blob__0::BYTEA AS blob, $x__0 AS x, $id__0::INTEGER AS id) AS data WHERE t.id = data.id",
    );
  });

  it("renders bulk update iso created as timestamptz", () => {
    const update = new BulkUpdateStatement("contacts", ["created"], ["id"], [
      { fields: [{ name: "created", value: "2020-01-02T03:04:05.000Z" }], ids: [{ name: "id", value: 1 }] },
    ]);
    expect(renderer.render(update)).toBe(
      "UPDATE contacts SET created = data.created FROM (SELECT $created__0::TIMESTAMPTZ AS created, $id__0::INTEGER AS id) AS data WHERE contacts.id = data.id",
    );
  });

  it("renders bulk update base64 version as bytea", () => {
    const update = new BulkUpdateStatement("contacts", ["version"], ["id"], [
      { fields: [{ name: "version", value: "AA==" }], ids: [{ name: "id", value: 1 }] },
    ]);
    expect(renderer.render(update)).toBe(
      "UPDATE contacts SET version = data.version FROM (SELECT $version__0::BYTEA AS version, $id__0::INTEGER AS id) AS data WHERE contacts.id = data.id",
    );
  });

  it("renders alter, trigger, identity insert, and drop statements", () => {
    expect(
      renderer.render(
        new AlterTableStatement("users", {
          kind: "alterColumn",
          column: { name: "age", type: "int", default: new ColumnDefault("0"), notNull: new NotNull() },
        }),
      ),
    ).toBe("ALTER TABLE users ALTER COLUMN age TYPE INTEGER, ALTER COLUMN age SET DEFAULT 0, ALTER COLUMN age SET NOT NULL");
    expect(
      renderer.render(
        new AlterTableStatement("users", { kind: "alterColumn", column: { name: "age", type: "int" } }),
      ),
    ).toBe("ALTER TABLE users ALTER COLUMN age TYPE INTEGER, ALTER COLUMN age DROP DEFAULT, ALTER COLUMN age DROP NOT NULL");
    expect(
      renderer.render(
        new AlterTableStatement("users", { kind: "addColumn", column: { name: "email", type: "TEXT" } }),
      ),
    ).toBe("ALTER TABLE users ADD COLUMN email TEXT");
    expect(renderer.render(new DropTriggerStatement("tr_users", "users"))).toBe(
      "DROP TRIGGER IF EXISTS tr_users ON users",
    );
    expect(renderer.render(new CreateTriggerStatement("users", "tr_users", "updated", "id", "NOW()"))).toBe(
      `-- Shared updated_at function
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated = NOW() AT TIME ZONE 'UTC';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tr_users BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at()`,
    );
    const insert = new InsertStatement("users", [{ name: "id", value: 1 }, { name: "name", value: "ada" }]);
    expect(renderer.render(new IdentityInsertStatement("users", "id", [insert], true))).toBe(
      `INSERT INTO users (id, name) VALUES (1, ada);
SELECT setval(pg_get_serial_sequence('users', 'id'), (SELECT MAX("id") FROM users))`,
    );
    expect(renderer.render(new IdentityInsertStatement("users", "id", [insert]))).toBe(
      "INSERT INTO users (id, name) VALUES (1, ada);",
    );
    expect(renderer.render(new IdentityInsertStatement("users", "id", [], true))).toBe("");
    expect(renderer.render(new DropRoutineStatement("fn_users"))).toBe("DROP FUNCTION IF EXISTS fn_users");
  });

  it("renders create/read/update stored procedure statements", () => {
    expect(
      renderer.render(
        new CreateCreateStoredProcedureStatement("CreateUsers", "users", ["id", "name"], [{ name: "name", type: "TEXT" }], "id", "INT", ["name"]),
      ),
    ).toContain("CREATE OR REPLACE FUNCTION CreateUsers");
    expect(
      renderer.render(
        new CreateReadStoredProcedureStatement("ReadUsers", "users", ["id", "name"], [], "id", "INT", [], []),
      ),
    ).toContain("ORDER BY t.id");
    expect(
      renderer.render(
        new CreateReadStoredProcedureStatement(
          "ReadUsersById",
          "users",
          ["id", "name"],
          [{ name: "id", type: "INT" }],
          "id",
          "INT",
          [],
          ["id"],
        ),
      ),
    ).toContain("WHERE t.id = ReadUsersById.id");
    expect(
      renderer.render(
        new CreateUpdateStoredProcedureStatement(
          "UpdateUsersByIdVersion",
          "users",
          ["id", "name", "version"],
          [{ name: "id", type: "INT" }, { name: "version", type: "INT" }, { name: "name", type: "TEXT" }],
          "id",
          "INT",
          ["name"],
          ["id", "version"],
        ),
      ),
    ).toContain("t.id = UpdateUsersByIdVersion.id AND t.version = UpdateUsersByIdVersion.version");
    expect(
      renderer.render(
        new CreateUpdateStoredProcedureStatement(
          "UpdateUsersAudit",
          "users",
          ["id", "name", "updated"],
          [{ name: "id", type: "INT" }, { name: "name", type: "TEXT" }, { name: "new_updated", type: "TIMESTAMPTZ" }],
          "id",
          "INT",
          ["name"],
          ["id"],
          false,
          "updated",
        ),
      ),
    ).toContain("updated = UpdateUsersAudit.new_updated");
    expect(
      renderer.render(
        new CreateUpdateStoredProcedureStatement(
          "UpdateUsersAuditMissing",
          "users",
          ["id", "name", "updated"],
          [{ name: "id", type: "INT" }, { name: "name", type: "TEXT" }],
          "id",
          "INT",
          ["name"],
          [],
          false,
          "updated",
        ),
      ),
    ).toContain("UPDATE users t");
    expect(
      renderer.render(
        new CreateDeleteStoredProcedureStatement(
          "DeleteUsersById",
          "users",
          ["id"],
          [{ name: "id", type: "BIGINT" }],
          "id",
          "INT",
          [],
          ["id"],
        ),
      ),
    ).toContain("id BIGINT");
    expect(
      renderer.render(
        new CreateDeleteStoredProcedureStatement("DeleteUsersByKey", "users", ["id"], [], "id", "INT", [], []),
      ),
    ).toContain("WHERE t.id = DeleteUsersByKey.id");
    expect(
      renderer.render(
        new CreateReadStoredProcedureStatement("ReadUsersByName", "users", ["id", "name"], [], "id", "INT", [], ["name"]),
      ),
    ).toContain("name INT");
    expect(
      renderer.render(
        new CreateDeleteStoredProcedureStatement("DeleteUsersByName", "users", ["id"], [], "id", "INT", [], ["name"]),
      ),
    ).toContain("name INT");
    const payload = { name: "payload", type: "jsonb" };
    expect(
      renderer.render(new CreateBulkCreateStoredProcedureStatement("BulkCreateUsers", "users", [payload], payload, "id", "INT")),
    ).toContain("jsonb_to_recordset");
    expect(
      renderer.render(new CreateBulkUpdateStoredProcedureStatement("BulkUpdateUsers", "users", [payload], payload, "id", "INT")),
    ).toContain("jsonb_to_recordset");
    expect(
      renderer.render(
        new CreateBulkDeleteStoredProcedureStatement(
          "BulkDeleteUsers",
          "users",
          [{ name: "id", type: "INT" }],
          { name: "payload", type: "jsonb" },
          "id",
          "INT",
        ),
      ),
    ).toContain("jsonb_to_recordset");
  });
});
