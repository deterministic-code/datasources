import assert from "node:assert/strict";
import { describe, it } from "vitest";
import { parse, stringify } from "yaml";
import { memoryReader } from "@deterministic-code/generators-common/deterministic-reader";
import { generate as generateSql } from "@deterministic-code/datasources-code-generators/sql/generate-sql";
import { generate as generateStoredProcedures } from "@deterministic-code/datasources-code-generators/sql/generate-stored-procedures";
import "./register-sql-generate.ts";

const TYPES_YAML = `types:
  - user:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
        - created:
            type: datetime
        - updated:
            type: datetime
`;

const ctx = (settings: Record<string, string>) => ({
  reader: memoryReader({ "types.yaml": TYPES_YAML }),
  settings,
});

const names = (
  entries: { filename: string }[],
): string[] => entries.map((e) => e.filename).sort();

const body = (entry: { content?: string; contents?: string } | undefined): string =>
  entry === undefined ? "" : "contents" in entry && entry.contents !== undefined ? String(entry.contents) : String(entry.content ?? "");

const postgresOn = {
  "datasource.use_stored_procedures": "true",
};

describe("generate-sql datasource.use_stored_procedures", () => {
  it("emits stored-procedure migrations when the flag is true on postgres", async () => {
    const files = names(await generateSql(ctx(postgresOn), ["postgres"]));
    assert.ok(files.includes("postgres/migrations/0001_initial_up.sql"));
    assert.ok(
      files.includes("postgres/migrations/0002_stored_procedures_up.sql"),
    );
    assert.ok(
      files.includes("postgres/migrations/0002_stored_procedures_down.sql"),
    );
  });

  it("omits stored-procedure migrations when the flag is absent", async () => {
    const files = names(
      await generateSql(ctx({}), ["postgres"]),
    );
    assert.ok(files.includes("postgres/migrations/0001_initial_up.sql"));
    assert.equal(
      files.some((f) => f.includes("stored_procedures")),
      false,
    );
  });

});

const identityYaml = `types:
  - person:
      tags: [datasource_type]
      inherits: set
      fields:
        - id:
            type: integer
            is_id: true
        - code:
            type: integer
        - email:
            type: string
  - link:
      tags: [datasource_type]
      inherits: set
      ids: [left_id, right_id]
      fields:
        - left_id:
            type: integer
        - right_id:
            type: integer
  - country:
      tags: [datasource_type]
      inherits: set
      fields:
        - name:
            type: string
`;

const identityDatasource = `includes:
  - types:
      filter: tag == "datasource_type"
types:
  - country:
      fields:
        - id:
            is_fixed_id: true
            is_readonly: true
`;

const identityCtx = {
  reader: memoryReader({
    "types.yaml": identityYaml,
    "datasource.yaml": identityDatasource,
  }),
  settings: {},
};

const upBody = async (
  settings: Record<string, string> = {},
) => {
  const files = await generateSql({
    reader: identityCtx.reader,
    settings,
  }, ["postgres"]);
  const up = files.find((e) => e.filename.endsWith("0001_initial_up.sql"));
  assert.ok(up, "expected initial up migration");
  return "contents" in up ? String(up.contents) : up.content;
};

describe("generate-sql identity keys", () => {
  it("uses is_id as a generated primary key", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "people"/);
    assert.match(sql, /"id" INTEGER GENERATED BY DEFAULT AS IDENTITY/);
    assert.match(sql, /CONSTRAINT "people_primary_key" PRIMARY KEY/);
    assert.match(sql, /"code" INTEGER NOT NULL/);
    assert.match(sql, /"email"/);
  });

  it("emits a composite primary key when ids lists multiple columns", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "links"/);
    assert.match(sql, /"left_id" INTEGER NOT NULL/);
    assert.match(sql, /"right_id" INTEGER NOT NULL/);
    assert.match(
      sql,
      /CONSTRAINT "links_primary_key" PRIMARY KEY \("left_id", "right_id"\)/,
    );
    assert.doesNotMatch(sql, /CREATE TABLE "links"[\s\S]*GENERATED BY DEFAULT AS IDENTITY/);
  });

  it("emits a plain primary key when is_fixed_id is set", async () => {
    const sql = await upBody();
    assert.match(sql, /CREATE TABLE "countries"/);
    assert.match(sql, /"id" INTEGER NOT NULL/);
    assert.match(sql, /CONSTRAINT "countries_primary_key" PRIMARY KEY \("id"\)/);
    assert.doesNotMatch(sql, /CREATE TABLE "countries"[\s\S]*GENERATED BY DEFAULT AS IDENTITY/);
  });

});

describe("generate-stored-procedures datasource.use_stored_procedures", () => {
  it("emits procedure migrations when the flag is true", async () => {
    const files = names(await generateStoredProcedures(ctx(postgresOn), ["postgres"]));
    assert.deepEqual(files, [
      "postgres/migrations/0002_stored_procedures_down.sql",
      "postgres/migrations/0002_stored_procedures_up.sql",
    ]);
    const up = body(
      (await generateStoredProcedures(ctx(postgresOn), ["postgres"])).find((entry) =>
        entry.filename.endsWith("_stored_procedures_up.sql"),
      ),
    );
    assert.ok(up.includes("read_users"));
    assert.ok(up.includes("bulk_create_users"));
    assert.ok(up.includes("CREATE OR REPLACE"));
  });

  it("emits nothing when the flag is absent", async () => {
    const files = await generateStoredProcedures(ctx({}), ["postgres"]);
    assert.deepEqual(files, []);
  });
});

describe("generate-sql version diffs", () => {

  it("replaces stored procedures when a later version adds a column", async () => {
    const first = "version-20261016T000000Z-001/diff.yaml";
    const second = "version-20261016T000000Z-002/diff.yaml";
    const nextYaml = `types:
  - user:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
        - created:
            type: datetime
        - updated:
            type: datetime
        - notes:
            type: string
`;
    const entries = await generateSql(
      {
        reader: memoryReader({
          "types.yaml": nextYaml,
          "datasource.yaml": `version: 1.0.0
includes:
  - types:
      filter: tag == "datasource_type" || tag == "view_type"
types: []
`,
          [first]: stringify({ "types.yaml": { added: true, content: parse(TYPES_YAML) } }),
          [second]: stringify({ "types.yaml": parse(nextYaml) }),
        }),
        settings: {
          "version.diffs": `${first}\n${second}`,
          "datasource.use_stored_procedures": "true",
        },
      },
      ["postgres"],
    );
    const up2 = body(entries.find((entry) => entry.filename === "postgres/migrations/0002_up.sql"));
    const down2 = body(entries.find((entry) => entry.filename === "postgres/migrations/0002_down.sql"));
    assert.ok(up2.includes("notes"));
    assert.ok(up2.includes("CREATE OR REPLACE"));
    assert.ok(down2.includes("CREATE OR REPLACE"));
  });

  it("throws when the selected dialect has neither an engine file nor datasource.yaml", async () => {
    const path = "version-20261016T000000Z-001/diff.yaml";
    await assert.rejects(
      () =>
        generateSql(
          {
            reader: memoryReader({
              "types.yaml": TYPES_YAML,
              "datasource.sqlite.yaml": `version: 1.0.0
types:
  - user:
      fields:
        - email:
            type: string
`,
              [path]: stringify({ "types.yaml": { added: true, content: parse(TYPES_YAML) } }),
            }),
            settings: { "version.diffs": path },
          },
          ["postgres"],
        ),
      /postgres requires datasource\.postgres\.yaml or datasource\.yaml/,
    );
  });

  it("infers a reference column type from the parent id", async () => {
    const files = await generateSql(
      {
        reader: memoryReader({
          "types.yaml": `types:
  - gender:
      tags: [datasource_type]
      inherits: set
      fields:
        - name:
            type: string
            size: 128
  - contact:
      tags: [datasource_type]
      inherits: set
      fields:
        - gender_type_id:
            references: gender.id
`,
        }),
        settings: {},
      },
      ["postgres"],
    );
    const up = files.find((e) => e.filename.endsWith("0001_initial_up.sql"));
    assert.ok(up, "expected initial up migration");
    const sql = "contents" in up ? String(up.contents) : up.content;
    const contacts = sql.match(/CREATE TABLE "contacts" \(([\s\S]*?)\);/)?.[1];
    assert.ok(contacts, "expected contacts table body");
    assert.match(contacts, /"gender_type_id" INTEGER/);
    assert.doesNotMatch(contacts, /"gender_type_id" TEXT/);
  });

  it("infers a versioned reference column type from an inherited parent id", async () => {
    const typesYaml = `types:
  - base:
      fields:
        - id:
            type: integer
            is_id: true
  - gender:
      tags: [datasource_type]
      inherits: base
      fields:
        - name:
            type: string
            size: 128
  - contact:
      tags: [datasource_type]
      inherits: base
      fields:
        - gender_type_id:
            references: gender.id
`;
    const datasourceYaml = `version: 1.0.0
includes:
  - types:
      filter: tag == "datasource_type" || tag == "view_type"
types: []
`;
    const path = "version-20261016T000000Z-001/diff.yaml";
    const files = await generateSql(
      {
        reader: memoryReader({
          "types.yaml": typesYaml,
          "datasource.yaml": datasourceYaml,
          [path]: stringify({ "types.yaml": { added: true, content: parse(typesYaml) } }),
        }),
        settings: { "version.diffs": path },
      },
      ["postgres"],
    );
    const up = files.find((e) => e.filename.endsWith("0001_up.sql"));
    assert.ok(up, "expected versioned up migration");
    const sql = "contents" in up ? String(up.contents) : up.content;
    const contacts = sql.match(/CREATE TABLE "contacts" \(([\s\S]*?)\);/)?.[1];
    assert.ok(contacts, "expected contacts table body");
    assert.match(contacts, /"gender_type_id" INTEGER/);
    assert.doesNotMatch(contacts, /"gender_type_id" TEXT/);
  });

});
