import {
  ColumnDefault,
  CreateTableStatement,
  CreateTableStatementRenderer,
  type Column,
  type IStatement,
} from "@datasources/core";
import { PostgresDriver } from "./PostgresDriver.ts";

const canonical = new Set(["int", "uuid", "string", "datetime", "bool", "decimal", "float", "binary"]);

export class PostgresStatementFactory extends CreateTableStatementRenderer {
  protected typeName(column: Column): string {
    return canonical.has(column.type) ? new PostgresDriver().columnType(column.type) : column.type;
  }

  protected columnDefault(column: Column): string {
    return column.type === "bool" && column.default?.value === "1"
      ? super.columnDefault({ ...column, default: new ColumnDefault("TRUE", column.default.name) })
      : super.columnDefault(column);
  }

  protected identity(column: Column): string {
    return column.identity ? " GENERATED BY DEFAULT AS IDENTITY" : "";
  }

  transform(statement: IStatement): IStatement {
    return statement instanceof CreateTableStatement && statement.table != null
      ? new CreateTableStatement(this.render(statement))
      : statement;
  }
}
