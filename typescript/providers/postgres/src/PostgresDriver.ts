import {
  DatasourceError,
  StatementTextRenderer,
  type Cell,
  type Column,
  type DatasourceOptions,
  type ICommand,
  type IConnection,
  type IDriver,
  type Information,
  type ITransaction,
  type IsolationLevel,
  type RoutineParameter,
  type TypeConverter,
} from "@deterministic-code/datasources";
import { PostgresConnection } from "./connection.ts";
import { PostgresCommand } from "./command.ts";
import { PostgresTransaction } from "./transaction.ts";
import { PostgresRowTypeConverters } from "./converters/PostgresRowTypeConverters.ts";
import { PostgresStatementRenderer } from "./PostgresStatementRenderer.ts";
import { columnTypes } from "./columnTypes.ts";
import { applyKeywords } from "./applyKeywords.ts";
import { TypeMap } from "./TypeMap.ts";
import { DefaultValueConverter } from "./DefaultValueConverter.ts";

export { columnTypes };

const statements = new StatementTextRenderer(t => new PostgresStatementRenderer(t), undefined, undefined, undefined, applyKeywords);
const types = new TypeMap({
  string: "TEXT",
  character: "CHAR(1)",
  integer: "INTEGER",
  unsignedinteger: "BIGINT",
  smallinteger: "SMALLINT",
  unsignedsmallinteger: "INTEGER",
  biginteger: "BIGINT",
  unsignedbiginteger: "NUMERIC(20)",
  float: "DOUBLE PRECISION",
  decimal: "NUMERIC",
  boolean: "BOOLEAN",
  datetime: "TIMESTAMPTZ",
  binary: "BYTEA",
  uuid: "UUID",
  reference: "INTEGER",
});
const defaults = new DefaultValueConverter({
  newId: () => "gen_random_uuid()",
  now: () => "LOCALTIMESTAMP",
  utcNow: () => `(NOW() AT TIME ZONE 'UTC')`,
  booleanOn: "TRUE",
  booleanOff: "FALSE",
  hex: (arg) => `'\\x${arg}'`,
  hexReverse: /^'\\x(.*)'$/,
});

export class PostgresDriver implements IDriver {
  static readonly procedurePayloadType = "jsonb";
  static applyKeywords = applyKeywords;
  static quote = (name: string): string => `"${name}"`;
  static nativeType = (column: Column): string =>
    column.field ? types.convertField(column.field) : columnTypes[column.type] ?? column.type;
  static nativeDefault = (column: Column): string =>
    column.default == null
      ? ""
      : column.field === undefined
        ? column.default.value
        : defaults.convert(column.field.type, column.default.value) ?? column.default.value;
  static utcNow = (): string => defaults.convert("datetime", "UtcNow") ?? "";
  static nativeParam = (parameter: RoutineParameter): string =>
    parameter.type === "payload"
      ? PostgresDriver.procedurePayloadType
      : parameter.field
        ? types.convertField(parameter.field)
        : types.dictionary[parameter.type] ?? parameter.type;
  static nativeSpec = (spec: string): string =>
    spec === "payload" ? PostgresDriver.procedurePayloadType : types.dictionary[spec] ?? spec;

  readonly statementRenderer = statements;
  readonly information: Information = {
    descriptions: [
      "PostgreSQL server driver.",
      "Full connection, command, transaction, and repository support.",
    ],
    overrides: [
      "Overrides SelectInsertedIdStatement to SELECT setval(pg_get_serial_sequence('{table}', '{column}'), MAX(\"{column}\")) AS {column}",
      "Overrides CreateTableStatement identity to GENERATED BY DEFAULT AS IDENTITY",
      "Overrides CreateTableStatement boolean defaults (0/1 → TRUE/FALSE)",
      "Overrides CreateTableStatement type mapping (int→INTEGER, uuid→UUID, string→TEXT, bool→BOOLEAN, decimal→NUMERIC, float→DOUBLE PRECISION, datetime→TIMESTAMPTZ, binary→BYTEA)",
      "Overrides CreateCreateStoredProcedureStatement to PROCEDURE Create{Plural}",
      "Overrides CreateReadStoredProcedureStatement to PROCEDURE Read{Plural}By{Properties}",
      "Overrides CreateUpdateStoredProcedureStatement to PROCEDURE Update{Plural}By{Properties}",
      "Overrides CreateDeleteStoredProcedureStatement to PROCEDURE Delete{Plural}By{Properties}",
      "Overrides CreateBulkCreateStoredProcedureStatement to PROCEDURE BulkCreate{Plural}",
      "Overrides CreateBulkUpdateStoredProcedureStatement to PROCEDURE BulkUpdate{Plural}",
      "Overrides CreateBulkDeleteStoredProcedureStatement to PROCEDURE BulkDelete{Plural}",
    ],
    changeLogs: [],
  };
  rowTypeConverters: Record<string, TypeConverter<Cell, Cell>> = PostgresRowTypeConverters;
  readonly quoteLeft = '"';
  readonly quoteRight = '"';
  readonly typeConverter = types;
  readonly defaultValueConverter = defaults;
  columnType = (name: string): string =>
    columnTypes[name] ??
    (() => {
      throw new DatasourceError(`Unknown postgres type "${name}"`);
    })();
  connection = (options?: DatasourceOptions): IConnection =>
    PostgresConnection.from(options);
  command = (connection: IConnection): ICommand =>
    new PostgresCommand(connection as PostgresConnection, statements);
  transaction = (
    connection: IConnection,
    isolation: IsolationLevel = "readCommitted",
  ): ITransaction =>
    new PostgresTransaction(connection as PostgresConnection, isolation);
}
