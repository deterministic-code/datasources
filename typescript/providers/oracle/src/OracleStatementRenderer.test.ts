import {
  AlterTableStatement,
  CreateBulkDeleteStoredProcedureStatement,
  CreateCreateStoredProcedureStatement,
  CreateReadStoredProcedureStatement,
  CreateTableStatement,
  CreateUpdateStoredProcedureStatement,
  CreateTriggerStatement,
  DropIndexStatement,
  DropTableStatement,
  DropTriggerStatement,
  StatementTextRenderer,
} from "@deterministic-code/datasources";
import { describe, expect, it } from "vitest";
import { OracleStatementRenderer } from "./OracleStatementRenderer.ts";

describe("OracleStatementRenderer", () => {
  const renderer = new StatementTextRenderer(t => new OracleStatementRenderer(t));

  it("renders create, alter, drop, and trigger statements", () => {
    expect(
      renderer.render(new CreateTableStatement("users", [{ name: "id", type: "INTEGER", identity: true }])),
    ).toBe("CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY)");
    expect(
      renderer.render(new CreateTableStatement("users", [{ name: "id", type: "INTEGER" }])),
    ).toBe("CREATE TABLE users (id INTEGER)");
    expect(
      renderer.render(
        new AlterTableStatement("users", { kind: "addColumn", column: { name: "email", type: "TEXT" } }),
      ),
    ).toBe("ALTER TABLE users ADD (email TEXT)");
    expect(
      renderer.render(
        new AlterTableStatement("users", { kind: "alterColumn", column: { name: "age", type: "INTEGER" } }),
      ),
    ).toBe("ALTER TABLE users MODIFY (age INTEGER)");
    expect(
      renderer.render(new AlterTableStatement("users", { kind: "dropColumn", name: "email" })),
    ).toBe("ALTER TABLE users DROP COLUMN email");
    expect(
      renderer.render(
        new AlterTableStatement("users", { kind: "renameColumn", from: "old", to: "new" }),
      ),
    ).toBe("ALTER TABLE users RENAME COLUMN old TO new");
    expect(renderer.render(new DropIndexStatement("ix_users_email", "users"))).toBe("DROP INDEX ix_users_email");
    expect(renderer.render(new DropTableStatement("users"))).toBe(
      `BEGIN EXECUTE IMMEDIATE 'DROP TABLE users CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/`,
    );
    expect(renderer.render(new CreateTriggerStatement("users", "tr_users", "updated", "id", "SYS_EXTRACT_UTC(SYSTIMESTAMP)"))).toBe(
      `CREATE OR REPLACE TRIGGER tr_users
BEFORE UPDATE ON users
FOR EACH ROW
BEGIN
  :NEW.updated := SYS_EXTRACT_UTC(SYSTIMESTAMP);
END;
/`,
    );
    expect(renderer.render(new DropTriggerStatement("tr_users", "users"))).toBe("DROP TRIGGER tr_users");
  });

  it("renders create/read/update stored procedure statements", () => {
    expect(
      renderer.render(
        new CreateCreateStoredProcedureStatement("CreateUsers", "users", ["id", "name"], [{ name: "name", type: "TEXT" }], "id", "INT", ["name"]),
      ),
    ).toContain("CREATE OR REPLACE PROCEDURE CreateUsers");
    expect(
      renderer.render(
        new CreateReadStoredProcedureStatement("ReadUsers", "users", ["id", "name"], [], "id", "INT", [], []),
      ),
    ).toContain("ORDER BY t.id");
    expect(
      renderer.render(
        new CreateReadStoredProcedureStatement(
          "ReadUsersById",
          "users",
          ["id", "name"],
          [{ name: "id", type: "INT" }],
          "id",
          "INT",
          [],
          ["id"],
        ),
      ),
    ).toContain("WHERE t.id = id");
    expect(
      renderer.render(
        new CreateUpdateStoredProcedureStatement(
          "UpdateUsersByIdVersion",
          "users",
          ["id", "name", "version"],
          [{ name: "id", type: "INT" }, { name: "version", type: "INT" }, { name: "name", type: "TEXT" }],
          "id",
          "INT",
          ["name"],
          ["id", "version"],
        ),
      ),
    ).toContain("t.id = id AND t.version = version");
    expect(
      renderer.render(
        new CreateBulkDeleteStoredProcedureStatement(
          "BulkDeleteUsers",
          "users",
          [{ name: "id", type: "INT" }],
          { name: "payload", type: "CLOB" },
          "id",
          "INT",
        ),
      ),
    ).toContain("JSON_TABLE");
  });
});
