const TOKEN =
  /('(?:''|[^'])*')|(`(?:``|[^`])*`)|("(?:""|[^"])*")|(--[^\n]*)|(\/\*[\s\S]*?\*\/)|(?<word>[A-Za-z_][A-Za-z0-9_]*)/g;

const SNAKE = /^[a-z][a-z0-9]*(?:_[a-z][a-z0-9]*)*$/;

export const isKeyword = (name: string): boolean => KEYWORDS.has(name.toUpperCase());

export const isVerbatim = (name: string): boolean => !SNAKE.test(name);

export const applyKeywords = (
  sql: string,
  keyword: (word: string) => string,
): string =>
  sql.replace(TOKEN, (match, _s, _b, _d, _lc, _bc, word) =>
    word !== undefined && isKeyword(word) ? keyword(word) : match,
  );
