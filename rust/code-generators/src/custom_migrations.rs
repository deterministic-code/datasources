use crate::generate_entry::GenerateEntry;
use datasources::{DatasourceError, Result};
use regex::Regex;
use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

static FILENAME: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^(\d+)_([A-Za-z0-9][A-Za-z0-9_-]*)_(up|down)\.sql$").expect("fn"));

struct Slot {
    order: i32,
    name: String,
    up: Option<String>,
    down: Option<String>,
}

pub fn of(
    files: &HashMap<String, String>,
    dialect: &str,
    deterministic_dir: Option<&str>,
) -> Result<Vec<GenerateEntry>> {
    let Some(dir) = deterministic_dir.filter(|d| !d.is_empty()) else {
        return Ok(Vec::new());
    };
    let prefix = format!("{}/custom/{dialect}/", dir.trim_end_matches(['/', '\\']));
    let alt = format!("custom/{dialect}/");
    let mut slots: HashMap<String, Slot> = HashMap::new();
    for (path, content) in files {
        let rel = if let Some(rest) = path.strip_prefix(&prefix) {
            rest
        } else if let Some(rest) = path.strip_prefix(&alt) {
            rest
        } else {
            continue;
        };
        if rel.contains('/') || rel.contains('\\') {
            continue;
        }
        let Some(caps) = FILENAME.captures(rel) else {
            return Err(DatasourceError::message(format!(
                "discoverCustomMigrations: {path} does not match expected pattern <order>_<name>_(up|down).sql"
            )));
        };
        let order: i32 = caps[1].parse().unwrap_or(0);
        if !(1..=999).contains(&order) {
            return Err(DatasourceError::message(format!(
                "discoverCustomMigrations: {path} has order {order}; must be in [1, 999]"
            )));
        }
        let name = caps[2].to_string();
        let side = &caps[3];
        let key = format!("{order}|{name}");
        let slot = slots.entry(key).or_insert_with(|| Slot {
            order,
            name: name.clone(),
            up: None,
            down: None,
        });
        if side == "up" {
            if slot.up.is_some() {
                return Err(DatasourceError::message(format!(
                    "discoverCustomMigrations: duplicate up file for order={order} name={name}"
                )));
            }
            slot.up = Some(content.clone());
        } else {
            if slot.down.is_some() {
                return Err(DatasourceError::message(format!(
                    "discoverCustomMigrations: duplicate down file for order={order} name={name}"
                )));
            }
            slot.down = Some(content.clone());
        }
    }
    let missing: Vec<String> = slots
        .values()
        .flat_map(|slot| {
            let mut list = Vec::new();
            if slot.up.is_none() {
                list.push(format!("missing _up.sql counterpart for {}", slot.name));
            }
            if slot.down.is_none() {
                list.push(format!("missing _down.sql counterpart for {}", slot.name));
            }
            list
        })
        .collect();
    if !missing.is_empty() {
        return Err(DatasourceError::message(format!(
            "discoverCustomMigrations: {} mismatched up/down pair(s):\n  {}",
            missing.len(),
            missing.join("\n  ")
        )));
    }
    let mut ordered: Vec<&Slot> = slots.values().collect();
    ordered.sort_by(|a, b| a.order.cmp(&b.order).then_with(|| a.name.cmp(&b.name)));
    let mut seen = HashSet::new();
    let mut entries = Vec::new();
    for slot in ordered {
        for (side, body) in [("up", slot.up.as_deref().unwrap()), ("down", slot.down.as_deref().unwrap())] {
            let filename = format!(
                "{:010}_custom_{:03}_{}_{side}.sql",
                slot.order, slot.order, slot.name
            );
            if !seen.insert(filename.clone()) {
                return Err(DatasourceError::message(format!(
                    "custom migration filename collision for dialect '{dialect}': {filename} is generated by both an included datasource and this project"
                )));
            }
            entries.push(GenerateEntry::new(format!("{dialect}/migrations/{filename}"), body));
        }
    }
    Ok(entries)
}
