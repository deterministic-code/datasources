use std::collections::HashMap;

const TYPES_YAML: &str = r#"
types:
  - user:
      tags: [datasource_type]
      inherits: set
      fields:
        - email:
            type: string
        - created:
            type: datetime
        - updated:
            type: datetime
"#;

fn files(types: &str, datasource: Option<&str>, seeds: Option<&str>) -> HashMap<String, String> {
    helpers::register_sql();
    let mut files = HashMap::from([("types.yaml".into(), types.to_string())]);
    if let Some(ds) = datasource {
        files.insert("datasource.yaml".into(), ds.into());
    }
    if let Some(seeds) = seeds {
        files.insert("datasource_seeds.yaml".into(), seeds.into());
    }
    files
}

fn names(entries: &[datasources_code_generators::GenerateEntry]) -> Vec<String> {
    let mut names: Vec<_> = entries.iter().map(|e| e.filename.clone()).collect();
    names.sort();
    names
}

#[test]
fn emits_stored_procedure_migrations_when_the_flag_is_true_on_postgres() {
    let listed = names(
        &generate_sql(
            &files(TYPES_YAML, None, None),
            &HashMap::from([("datasource.use_stored_procedures".into(), "true".into())]),
            &["postgres".into()],
        )
        .unwrap(),
    );
    assert!(listed.iter().any(|f| f == "postgres/migrations/0001_initial_up.sql"));
    assert!(listed.iter().any(|f| f == "postgres/migrations/0002_stored_procedures_up.sql"));
    assert!(listed.iter().any(|f| f == "postgres/migrations/0002_stored_procedures_down.sql"));
    let up = generate_sql(
        &files(TYPES_YAML, None, None),
        &HashMap::from([("datasource.use_stored_procedures".into(), "true".into())]),
        &["postgres".into()],
    )
    .unwrap()
    .into_iter()
    .find(|e| e.filename.ends_with("_stored_procedures_up.sql"))
    .unwrap()
    .content;
    assert!(up.contains("read_users"));
    assert!(up.contains("bulk_create_users"));
    assert!(up.contains("CREATE OR REPLACE"));
}

