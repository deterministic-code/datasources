const IDENTITY_YAML: &str = r#"
types:
  - person:
      tags: [datasource_type]
      inherits: set
      fields:
        - code:
            type: integer
        - email:
            type: string
  - link:
      tags: [datasource_type]
      inherits: set
      ids: [left_id, right_id]
      fields:
        - left_id:
            type: integer
        - right_id:
            type: integer
  - country:
      tags: [datasource_type]
      inherits: set
      fields:
        - name:
            type: string
"#;

const IDENTITY_DATASOURCE: &str = r#"
includes:
  - types:
      filter: tag == "datasource_type"
types:
  - country:
      fields:
        - id:
            is_fixed_id: true
            is_readonly: true
"#;

fn up_body() -> String {
    generate_sql(
        &files(IDENTITY_YAML, Some(IDENTITY_DATASOURCE), None),
        &HashMap::new(),
        &["postgres".into()],
    )
    .unwrap()
    .into_iter()
    .find(|e| e.filename.ends_with("0001_initial_up.sql"))
    .unwrap()
    .content
}

#[test]
fn uses_the_injected_set_id_as_a_generated_primary_key() {
    let sql = up_body();
    assert!(Regex::new(r#"CREATE TABLE "people""#).unwrap().is_match(&sql));
    assert!(Regex::new(r#""id" INTEGER GENERATED BY DEFAULT AS IDENTITY"#)
        .unwrap()
        .is_match(&sql));
    assert!(Regex::new(r#"CONSTRAINT "people_primary_key" PRIMARY KEY"#)
        .unwrap()
        .is_match(&sql));
    assert!(Regex::new(r#""code" INTEGER NOT NULL"#).unwrap().is_match(&sql));
    assert!(Regex::new(r#""email""#).unwrap().is_match(&sql));
}

#[test]
fn emits_a_composite_primary_key_when_ids_lists_multiple_columns() {
    let sql = up_body();
    assert!(Regex::new(r#"CREATE TABLE "links""#).unwrap().is_match(&sql));
    assert!(Regex::new(r#""left_id" INTEGER NOT NULL"#).unwrap().is_match(&sql));
    assert!(Regex::new(r#""right_id" INTEGER NOT NULL"#).unwrap().is_match(&sql));
    assert!(Regex::new(r#"CONSTRAINT "links_primary_key" PRIMARY KEY \("left_id", "right_id"\)"#)
        .unwrap()
        .is_match(&sql));
    let table = Regex::new(r#"CREATE TABLE "links"[\s\S]*?(CREATE TABLE|$)"#)
        .unwrap()
        .find(&sql)
        .map(|m| m.as_str().to_string())
        .unwrap_or_default();
    assert!(!table.contains("GENERATED BY DEFAULT AS IDENTITY"));
}

