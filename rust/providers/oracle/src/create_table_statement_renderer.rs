use datasources::{Column, CreateTableStatementTextRenderer};

pub struct OracleCreateTableStatementRenderer;

impl CreateTableStatementTextRenderer for OracleCreateTableStatementRenderer {
    fn quote(&self, name: &str) -> String {
        crate::OracleDriver::quote(name)
    }

    fn type_name(&self, column: &Column) -> String {
        crate::OracleDriver::native_type(column)
    }

    fn column_default(&self, column: &Column) -> String {
        match &column.default {
            None => String::new(),
            Some(value) if value.name.is_none() => {
                format!(" DEFAULT {}", crate::OracleDriver::native_default(column))
            }
            Some(value) => format!(
                " CONSTRAINT {} DEFAULT {}",
                self.quote(value.name.as_deref().unwrap_or("")),
                crate::OracleDriver::native_default(column)
            ),
        }
    }

    fn identity(&self, column: &Column) -> String {
        if column.identity {
            " GENERATED BY DEFAULT AS IDENTITY".into()
        } else {
            String::new()
        }
    }
}
