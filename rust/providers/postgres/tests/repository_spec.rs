use super::command::PostgresCommand;
use super::connection::PostgresConnection;
use datasources::{Column, Connection, CreateTableStatement, Text};
use datasources_sql_specs::RepositoryDialect;
use std::sync::Arc;
use std::time::SystemTime;
use tokio_postgres::NoTls;

fn quote(id: &str) -> String {
    format!("\"{}\"", id.replace('"', "\"\""))
}

fn map(canonical: &str) -> String {
    match canonical {
        "int" => "INTEGER",
        "uuid" => "UUID",
        "string" => "TEXT",
        "bool" => "BOOLEAN",
        "decimal" => "NUMERIC",
        "float" => "DOUBLE PRECISION",
        "datetime" => "TIMESTAMPTZ",
        "binary" => "BYTEA",
        _ => panic!("Unknown postgres type \"{canonical}\""),
    }
    .into()
}

fn dialect() -> RepositoryDialect {
    RepositoryDialect {
        provider: "postgres",
        quote: quote,
        create_table: |table, columns| {
            let mapped: Vec<Column> = columns
                .iter()
                .map(|column| {
                    let affinity = map(&column.type_name);
                    Column::new(
                        quote(&column.name),
                        if column.id {
                            format!("{affinity} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
                        } else {
                            affinity
                        },
                    )
                })
                .collect();
            CreateTableStatement::new(quote(table), &mapped, &[]).get_text()
        },
        field: super::converters::field,
        types: super::converters::row_type_converters,
    }
}

#[tokio::test]
async fn user_crud() {
    let Ok(url) = std::env::var("POSTGRES_URL") else {
        return;
    };
    for path in datasources_sql_specs::files() {
        let schema = format!(
            "ds_{:x}",
            SystemTime::now()
                .duration_since(SystemTime::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0)
        );
        let (client, connection) = tokio_postgres::connect(&url, NoTls).await.unwrap();
        tokio::spawn(async move {
            let _ = connection.await;
        });
        client
            .batch_execute(&format!("CREATE SCHEMA {schema}"))
            .await
            .unwrap();
        let conn = Arc::new(PostgresConnection::new(Some(url.clone()), Some(schema.clone())));
        conn.open().await.unwrap();
        let command = Arc::new(PostgresCommand::new(conn.clone()));
        datasources_sql_specs::run(&path, &dialect(), conn, command)
            .await
            .unwrap();
        client
            .batch_execute(&format!("DROP SCHEMA {schema} CASCADE"))
            .await
            .ok();
    }
}
