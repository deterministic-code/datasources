use crate::create_table_statement_renderer::PostgresCreateTableStatementRenderer;
use datasources::{
    CreateTableStatement, CreateTableStatementRenderer, SelectInsertedIdStatement, SelectStatement,
    Statement, Text,
};

pub struct PostgresStatementFactory;

pub enum Transformed<'a> {
    Same(&'a dyn Statement),
    Create(CreateTableStatement),
    Select(SelectStatement),
}

impl Transformed<'_> {
    pub fn get_text(&self) -> String {
        match self {
            Self::Same(statement) => statement.get_text(),
            Self::Create(statement) => statement.get_text(),
            Self::Select(statement) => statement.get_text(),
        }
    }
}

impl PostgresStatementFactory {
    pub fn transform<'a>(&self, statement: &'a dyn Statement) -> Transformed<'a> {
        if let Some(inserted) = statement.as_any().downcast_ref::<SelectInsertedIdStatement>() {
            return Transformed::Select(SelectStatement::text(format!(
                "SELECT lastval() AS {}",
                inserted.column
            )));
        }
        match statement.as_any().downcast_ref::<CreateTableStatement>() {
            Some(create) if create.table.is_some() => Transformed::Create(CreateTableStatement::text(
                PostgresCreateTableStatementRenderer.render(create),
            )),
            _ => Transformed::Same(statement),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::PostgresStatementFactory;
    use super::Transformed;
    use datasources::{
        Column, ColumnDefault, CreateTableStatement, DeleteStatement, ForeignKey, NotNull,
        PrimaryKey, ReferentialAction, Text,
    };

    #[test]
    fn transforms_create_table_and_passes_other_statements_through() {
        let columns = [
            Column::new("id", "INTEGER")
                .default(ColumnDefault::new("0", Some("df_id")))
                .not_null(NotNull::new(Some("nn_id"))),
            Column::new("user_id", "INTEGER"),
        ];
        let constraints = [
            PrimaryKey::new("pk_orders", &["id"]),
            ForeignKey::new(
                "fk_orders_user",
                &["user_id"],
                "users",
                &["id"],
                Some(ReferentialAction::Cascade),
                None,
            ),
        ];
        let create = CreateTableStatement::new("orders", &columns, &constraints);
        let factory = PostgresStatementFactory;
        let Transformed::Create(transformed) = factory.transform(&create) else {
            panic!("compiled create table");
        };
        assert!(transformed.table.is_none());
        assert_eq!(transformed.get_text(), create.get_text());
        assert!(matches!(
            factory.transform(&transformed),
            Transformed::Same(_)
        ));

        let raw = CreateTableStatement::text("x");
        assert!(matches!(factory.transform(&raw), Transformed::Same(_)));
        let delete = DeleteStatement::raw("DELETE FROM users", None);
        assert!(matches!(factory.transform(&delete), Transformed::Same(_)));
        let inserted = datasources::SelectInsertedIdStatement::new("users", "id");
        assert_eq!(
            factory.transform(&inserted).get_text(),
            "SELECT lastval() AS id"
        );
    }

    #[test]
    fn renders_identity() {
        let columns = [
            Column::new("id", "int").identity(),
            Column::new("is_enabled", "bool").default(ColumnDefault::new("1", None)),
            Column::new("is_disabled", "bool").default(ColumnDefault::new("0", Some("df_off"))),
            Column::new("amount", "decimal").default(ColumnDefault::new("1", None)),
            Column::new("flag", "bool").default(ColumnDefault::new("true", None)),
        ];
        let create = CreateTableStatement::new("users", &columns, &[]);
        let Transformed::Create(transformed) = PostgresStatementFactory.transform(&create) else {
            panic!("compiled create table");
        };
        assert_eq!(
            transformed.get_text(),
            "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY, is_enabled BOOLEAN DEFAULT TRUE, is_disabled BOOLEAN CONSTRAINT df_off DEFAULT FALSE, amount NUMERIC DEFAULT 1, flag BOOLEAN DEFAULT true)"
        );
        assert_eq!(
            create.get_text(),
            "CREATE TABLE users (id int, is_enabled bool DEFAULT 1, is_disabled bool CONSTRAINT df_off DEFAULT 0, amount decimal DEFAULT 1, flag bool DEFAULT true)"
        );
    }
}
