use crate::converters::field;
use crate::driver::column_sql;
use datasources::{Column, ColumnDefault, CreateTableStatementRenderer, Value};

pub struct PostgresCreateTableStatementRenderer;

impl CreateTableStatementRenderer for PostgresCreateTableStatementRenderer {
    fn type_name(&self, column: &Column) -> String {
        column_sql(&column.type_name)
            .map(str::to_string)
            .unwrap_or_else(|| column.type_name.clone())
    }

    fn column_default(&self, column: &Column) -> String {
        match (column.default.as_ref(), literal(column)) {
            (Some(value), Some(text)) => {
                self.write_default(Some(&ColumnDefault::new(text, value.name.as_deref())))
            }
            _ => self.write_default(column.default.as_ref()),
        }
    }

    fn identity(&self, column: &Column) -> String {
        if column.identity {
            " GENERATED BY DEFAULT AS IDENTITY".into()
        } else {
            String::new()
        }
    }
}

fn literal(column: &Column) -> Option<String> {
    let raw = column.default.as_ref()?.value.as_str();
    let number = raw.parse::<i64>().ok()?;
    let converter = field(&column.type_name)?;
    match converter.convert(&Value::Int(number)).ok()? {
        Value::Bool(true) => Some("TRUE".into()),
        Value::Bool(false) => Some("FALSE".into()),
        _ => None,
    }
}
